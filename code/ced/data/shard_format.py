"""The on-disk shard format, with numpy only (no torch), so tokenization can run in a separate
environment (one that has the HF `tokenizers` library).

A shard set is a directory written once by `ShardWriter`:

    tokens.bin      uint32  token ids of all documents, concatenated (uint16 when meta.json says
                            "token_dtype": "uint16"; absent means uint32)
    byte_lens.bin   uint8   UTF-8 bytes each token covers (for bpb), clipped to 255. Optional:
                            training never reads it (ShardPacker gives zeros without it)
    generated.bin   uint8   1 where the token is generated by the assistant (chat documents only)
    doc_starts.npy  int64   start offset of every document, plus the total length at the end
    doc_chat.npy    uint8   1 for chat-format documents (decoder positions by role)
    doc_source.npy  uint16  optional: index into meta.json["sources"] for every document
    loss_spans.bin  uint8   optional: the loss-span class of every token (below); absent means class 0 everywhere
    meta.json               document and token counts (and source names, when given)

The loss-span classes (loss_spans.bin; read by the per-token loss mask, DataConfig.loss_mask): one byte a token, fixed per document
when the set is built, so a row cut never moves a head or a tail: 0 loss in every arm (assistant and user turns, every web and code
document) 1 tool-output content beyond its first and last LOSS_SPANS_HEAD / LOSS_SPANS_TAIL (64) content tokens 2 the first 64 and last
64 content tokens of a tool output (the whole content at 128 or fewer) 3 always masked (tool definitions, system prompts, repeated
identical reads, hand-off blocks, the tool message's header and end tokens) 4-255 reserved: never in version 1.
(`<|im_start|>`, `user` with its newline) and tail (`<|im_end|>`, newline) are class 3 and its content follows the same 128 / 64 + 64 rule. The file's
version, head, tail and invariants are unchanged; only which messages the producer marks differs. "3": n3}}. Invariants (check_loss_spans, run when a
set is opened with a mask that reads the file): classes 1 and 2 only in chat documents; no class above 0 on a generated token; generated.bin strictly
0/1. The file is written by ShardWriter(... loss_spans=True) or by a builder of its own (tools/data/build_step2_base.py), and read only by the packer
under a span mode; every reader of before ignores it.

Two or more sets can be read as one (ShardUnion, open_shards; DataConfig.extra_shard_dirs): the documents of the first,
then those of the next, with the same fields as a ShardSet. The union's first epoch is read in one of two orders
(DataConfig.union_order): "permute" (the default, as the loader was built) or "sets_in_order" (long-data, 2026-10-30).

Compact build: `ShardWriter(... byte_lens=False)` writes no byte_lens.bin at all, so a set built straight at 64k
is already in the stored compact form (uint16 ids, no byte_lens.bin) that tools/data/compact_shards.py makes
from a uint32 build; its files are byte-identical to that conversion's (tests/test_item6_build.py). The default
(byte_lens=True) writes what it always wrote.

Token dtype: uint32 is the default and is not written to meta.json, so a default build's files are
byte-identical to those of earlier code (their recorded sha256 still hold). A uint16 set (every id
< 65,536, e.g. the 64k tokenizer's) records "token_dtype": "uint16"; `tools/data/compact_shards.py`
converts a uint32 set to one. Readers cast slices of `ShardSet.tokens` to int64 before arithmetic.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np

from ced.eval.tokenized import TokenizedDoc

TOKEN_DTYPES = {"uint32": np.uint32, "uint16": np.uint16}
DEFAULT_TOKEN_DTYPE = "uint32"

# The loss-span classes (module docstring): the file, its version, the classes' names as meta.json records them, and the
# per-token loss mask's modes (DataConfig.loss_mask) with, for each span mode, the classes whose targets keep their loss.
LOSS_SPANS_FILE = "loss_spans.bin"
LOSS_SPANS_VERSION = 1
LOSS_SPANS_HEAD = LOSS_SPANS_TAIL = 64
LOSS_SPAN_CLASSES = {"0": "loss", "1": "tool_content_middle", "2": "tool_content_head_tail", "3": "always_masked"}
LOSS_MASK_ALL, LOSS_MASK_ASSISTANT = "all", "assistant"
# MA-full keeps classes 0, 1 and 2; the head+tail arms (MA, MV, MN) keep 0 and 2; MA-mask keeps 0 (class 3 never)
LOSS_SPAN_KEEP = {"spans_full": (0, 1, 2), "spans_head_tail": (0, 2), "spans_mask": (0,)}
LOSS_MASK_MODES = (LOSS_MASK_ALL, LOSS_MASK_ASSISTANT, *LOSS_SPAN_KEEP)


def loss_span_table(mode: str) -> np.ndarray:
    """(256,) bool: whether a target of each class value keeps its loss under the span mode `mode` (False for 3 and for the
    reserved 4-255, which check_loss_spans refuses anyway)."""
    table = np.zeros(256, dtype=bool)
    table[list(LOSS_SPAN_KEEP[mode])] = True
    return table


def token_dtype_of(meta: dict) -> str:
    """The token file's dtype named by a shard set's meta.json (uint32 when absent)."""
    name = meta.get("token_dtype", DEFAULT_TOKEN_DTYPE)
    assert name in TOKEN_DTYPES, f"unknown token_dtype {name!r}"
    return name


def as_token_ids(ids, token_dtype: str) -> np.ndarray:
    """ids as the token file's dtype; asserts every id fits (no silent wrap-around)."""
    a = np.asarray(ids)
    if a.dtype != TOKEN_DTYPES[token_dtype] and len(a):
        a = a.astype(np.int64, copy=False)
        hi = np.iinfo(TOKEN_DTYPES[token_dtype]).max
        assert int(a.min()) >= 0 and int(a.max()) <= hi, \
            f"token id outside [0, {hi}] cannot be stored as {token_dtype} (min {int(a.min())}, max {int(a.max())})"
    return a.astype(TOKEN_DTYPES[token_dtype], copy=False)


class ShardWriter:
    def __init__(self, directory: str | Path, token_dtype: str = DEFAULT_TOKEN_DTYPE, byte_lens: bool = True,
                 loss_spans: bool = False):
        assert token_dtype in TOKEN_DTYPES, f"token_dtype must be one of {sorted(TOKEN_DTYPES)}"
        self.token_dtype = token_dtype
        self.write_byte_lens = byte_lens  # False: no byte_lens.bin (the compact stored form); callers still pass byte_lens
        self.dir = Path(directory)
        self.dir.mkdir(parents=True, exist_ok=True)
        names = ("tokens", "byte_lens", "generated") if byte_lens else ("tokens", "generated")
        self._files = {name: open(self.dir / f"{name}.bin", "wb") for name in names}
        # loss_spans True: also loss_spans.bin (module docstring), each document's classes given to add / add_arrays
        # (spans=; zeros when not given), and meta.json's "loss_spans" block with the classes' token counts. False (the
        # default): no such file and no key, every file as before.
        self._spans = open(self.dir / LOSS_SPANS_FILE, "wb") if loss_spans else None
        self._class_tokens = np.zeros(256, dtype=np.int64)
        self._starts = [0]
        self._chat = []
        self._source = []
        self.sources: list[str] = []

    def _write_spans(self, spans, generated, chat: bool, n: int) -> None:
        """One document's loss-span classes (n values) into loss_spans.bin, checked against check_loss_spans's
        invariants as they are written; spans None: class 0 everywhere. Nothing without loss_spans=True."""
        if self._spans is None:
            assert spans is None, "loss-span classes given to a ShardWriter made without loss_spans=True"
            return
        sp = np.zeros(n, dtype=np.uint8) if spans is None else np.asarray(spans)
        assert len(sp) == n and sp.dtype.kind in "iu" and (n == 0 or (int(sp.min()) >= 0 and int(sp.max()) <= 3)), \
            "loss-span classes: one value in 0..3 a token (4-255 are reserved in version 1)"
        sp = sp.astype(np.uint8, copy=False)
        gen = np.asarray(generated, dtype=np.uint8)
        assert chat or not bool(((sp == 1) | (sp == 2)).any()), "loss-span class 1 or 2 outside a chat document"
        assert not bool(((sp > 0) & (gen > 0)).any()), "a loss-span class above 0 on a generated token"
        self._class_tokens += np.bincount(sp, minlength=256)
        self._spans.write(sp.tobytes())

    def _ids(self, ids) -> bytes:
        if self.token_dtype == DEFAULT_TOKEN_DTYPE:  # unchecked, as before
            return np.asarray(ids, dtype=np.uint32).tobytes()
        return as_token_ids(ids, self.token_dtype).tobytes()

    def add(self, doc: TokenizedDoc, generated: list[int] | None = None, chat: bool = False, spans=None) -> None:
        n = len(doc.ids)
        if n == 0:
            return
        generated = generated if generated is not None else [0] * n
        assert len(generated) == n and (chat or not any(generated))
        self._write_spans(spans, generated, chat, n)
        self._files["tokens"].write(self._ids(doc.ids))
        if self.write_byte_lens:
            self._files["byte_lens"].write(np.minimum(np.asarray(doc.byte_lens), 255).astype(np.uint8).tobytes())
        self._files["generated"].write(np.asarray(generated, dtype=np.uint8).tobytes())
        self._starts.append(self._starts[-1] + n)
        self._chat.append(int(chat))

    def add_arrays(self, ids: np.ndarray, byte_lens: np.ndarray, generated: np.ndarray | None = None,
                   chat: bool = False, source: str | None = None, spans: np.ndarray | None = None) -> None:
        """Faster `add` for numpy arrays. byte_lens must already be exact (<= 255 each). spans: the document's loss-span
        classes (a writer made with loss_spans=True; None: class 0 everywhere)."""
        n = len(ids)
        if n == 0:
            return
        assert len(byte_lens) == n and int(np.max(byte_lens)) <= 255
        generated = np.zeros(n, dtype=np.uint8) if generated is None else generated
        assert len(generated) == n and (chat or not generated.any())
        self._write_spans(spans, generated, chat, n)
        self._files["tokens"].write(self._ids(ids))
        if self.write_byte_lens:
            self._files["byte_lens"].write(np.asarray(byte_lens, dtype=np.uint8).tobytes())
        self._files["generated"].write(np.asarray(generated, dtype=np.uint8).tobytes())
        self._starts.append(self._starts[-1] + n)
        self._chat.append(int(chat))
        if source is not None:
            if source not in self.sources:
                self.sources.append(source)
            self._source.append(self.sources.index(source))

    def close(self, extra_meta: dict | None = None) -> None:
        for f in self._files.values():
            f.close()
        np.save(self.dir / "doc_starts.npy", np.asarray(self._starts, dtype=np.int64))
        np.save(self.dir / "doc_chat.npy", np.asarray(self._chat, dtype=np.uint8))
        meta = {"n_docs": len(self._chat), "n_tokens": self._starts[-1]}
        if self._spans is not None:  # the span file's block (module docstring); absent without the file
            self._spans.close()
            meta["loss_spans"] = {"version": LOSS_SPANS_VERSION, "head": LOSS_SPANS_HEAD, "tail": LOSS_SPANS_TAIL,
                                  "classes": dict(LOSS_SPAN_CLASSES),
                                  "class_tokens": {str(c): int(self._class_tokens[c]) for c in range(4)}}
        if self.token_dtype != DEFAULT_TOKEN_DTYPE:
            meta["token_dtype"] = self.token_dtype
        if self._source:
            assert len(self._source) == len(self._chat), "give a source for every document or none"
            np.save(self.dir / "doc_source.npy", np.asarray(self._source, dtype=np.uint16))
            meta["sources"] = self.sources
        meta.update(extra_meta or {})
        assert token_dtype_of(meta) == self.token_dtype, "extra_meta names another token_dtype"
        (self.dir / "meta.json").write_text(json.dumps(meta, indent=1))


def check_index(doc_starts: np.ndarray, doc_chat: np.ndarray, doc_source, where) -> None:
    """The document index of a shard set, where every document boundary of training comes from (ced/train/batch_check.py
    checks every batch built from it). doc_starts is 1-D integer, one entry more than doc_chat (and doc_source, when
    present), starts at 0 and never decreases. An empty document (two equal starts) is allowed: the packer reads past it
    (ShardPacker._stream), and ShardWriter never writes one. ValueError naming the first offending document; whole-array
    numpy reductions, once when a set is opened."""
    s = np.asarray(doc_starts)
    if s.ndim != 1 or s.dtype.kind not in "iu" or len(s) < 1:
        raise ValueError(f"{where}: doc_starts.npy must be a 1-D integer array, not {s.dtype} of shape {s.shape}")
    if len(doc_chat) != len(s) - 1:
        raise ValueError(f"{where}: doc_chat.npy has {len(doc_chat)} documents, doc_starts.npy {len(s) - 1}")
    if doc_source is not None and len(doc_source) != len(s) - 1:
        raise ValueError(f"{where}: doc_source.npy has {len(doc_source)} documents, doc_starts.npy {len(s) - 1}")
    if int(s[0]) != 0:
        raise ValueError(f"{where}: doc_starts.npy starts at {int(s[0])}, not 0 (tokens before it are in no document)")
    if len(s) > 1:
        down = np.diff(s) < 0
        if bool(down.any()):
            i = int(np.argmax(down))
            raise ValueError(f"{where}: doc_starts.npy decreases at document {i} (start {int(s[i])}, next {int(s[i + 1])}): "
                             "document boundaries must not decrease")


class ShardSet:
    def __init__(self, directory: str | Path):
        d = Path(directory)
        self.meta = json.loads((d / "meta.json").read_text())
        self.token_dtype = token_dtype_of(self.meta)
        # Slices keep the file's dtype (uint32 or uint16): cast to int64 before arithmetic or torch.
        self.tokens = np.memmap(d / "tokens.bin", dtype=TOKEN_DTYPES[self.token_dtype], mode="r")
        # Byte lengths are only needed for bpb (eval); training runs may stage the set without them.
        self.byte_lens = np.memmap(d / "byte_lens.bin", dtype=np.uint8, mode="r") if (d / "byte_lens.bin").exists() else None
        self.generated = np.memmap(d / "generated.bin", dtype=np.uint8, mode="r")
        self.doc_starts = np.load(d / "doc_starts.npy")
        self.doc_chat = np.load(d / "doc_chat.npy")
        self.n_docs = len(self.doc_chat)
        self.n_tokens = int(self.doc_starts[-1])
        self.directory = d
        assert len(self.tokens) == self.n_tokens, \
            f"{d}: tokens.bin holds {len(self.tokens)} {self.token_dtype} ids, doc_starts says {self.n_tokens}"
        assert len(self.generated) == self.n_tokens, f"{d}: generated.bin length differs from doc_starts"
        assert self.byte_lens is None or len(self.byte_lens) == self.n_tokens, f"{d}: byte_lens.bin length differs"
        self.doc_source = np.load(d / "doc_source.npy") if (d / "doc_source.npy").exists() else None
        check_index(self.doc_starts, self.doc_chat, self.doc_source, d)

    @property
    def has_loss_spans(self) -> bool:
        """Whether the set has loss_spans.bin (module docstring). Nothing is opened."""
        return (self.directory / LOSS_SPANS_FILE).exists()

    @property
    def loss_spans(self):
        """The loss-span classes (uint8 memmap, one a token), or None when the set has no loss_spans.bin. Opened at the first
        read only: a reader that never asks (every mask mode but the span modes) opens nothing."""
        if "_loss_spans" not in self.__dict__:
            self._loss_spans = (np.memmap(self.directory / LOSS_SPANS_FILE, dtype=np.uint8, mode="r")
                                if self.has_loss_spans and self.n_tokens else None)
        return self._loss_spans

    def fingerprint(self) -> str:
        """A cheap identity of the data, not of its storage. A resumed run checks it, so it cannot
        silently continue on other data.

        blake2b-128 over: doc_starts (int64 bytes), doc_chat (uint8 bytes), and the first and last
        65,536 token ids as little-endian uint32 bytes, whatever the file's dtype. So a uint16 copy
        of a uint32 set (same ids, same batches) has the same fingerprint, and a uint32 set's
        fingerprint is what it was before uint16 existed. Not covered: generated flags, byte_lens,
        doc_source, meta.json, tokens between the first and last 65,536."""
        import hashlib

        h = hashlib.blake2b(digest_size=16)
        h.update(self.doc_starts.tobytes())
        h.update(self.doc_chat.tobytes())
        h.update(np.asarray(self.tokens[:65536]).astype("<u4").tobytes())
        h.update(np.asarray(self.tokens[-65536:]).astype("<u4").tobytes())
        return h.hexdigest()


