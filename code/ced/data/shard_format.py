# The loss-span classes' invariants (module docstring), checked when a set is opened with a loss mask


LOSS_CHECK_CHUNK = 1 << 26  # tokens a pass reads at a time (64 Mi: about 128 MiB of host memory for two uint8 files)


def _doc_of(doc_starts: np.ndarray, position: int) -> int:
    """The document that holds token `position` (empty documents never do)."""
    return int(np.searchsorted(doc_starts, position, side="right") - 1)


def _chat_of_tokens(doc_starts: np.ndarray, doc_chat: np.ndarray, a: int, b: int) -> np.ndarray:
    """(b - a,) bool: whether each token of [a, b) is in a chat document (b > a)."""
    first, last = _doc_of(doc_starts, a), _doc_of(doc_starts, b - 1)
    lengths = np.diff(np.clip(doc_starts[first:last + 2], a, b))
    return np.repeat(np.asarray(doc_chat[first:last + 1]).astype(bool), lengths)


def check_loss_spans(shards, mode: str) -> dict:
    """The invariants a loss mask relies on, checked over a ShardSet or a ShardUnion when it is opened with DataConfig.loss_mask
    `mode` other than "all" (ShardPacker): ValueError naming the set, the document and the token otherwise. Returns the
    data identity of the classes ({"mode", "parts": [None, or {"version", "head", "tail", "class_tokens", "blake2b"} of a
    part with loss_spans.bin]}; "blake2b": the 128-bit blake2b of the file's bytes, read in the same pass), which the
    trainer keeps in its checkpoints (Trainer.data_state), so a resume on another span file is refused, also one with the
    same class counts.
    - Every mode: generated.bin strictly 0/1 (in "assistant" mode on every part; in a span mode on every part with a span
      file, the only parts a span mode reads).
    - A span mode: some part has loss_spans.bin; each such part's meta.json has the "loss_spans" block of version 1 with
      the classes of LOSS_SPAN_CLASSES, the file has one byte a token, every value is 0..3, classes 1 and 2 are only in
      chat documents, no class above 0 is on a generated token, and the class counts equal meta.json's "class_tokens"
      when it has them.
    Numpy only, in chunks of LOSS_CHECK_CHUNK tokens; one pass over the files read (about 1-2 s for a 320M-token set, modelled)."""
    if mode not in LOSS_MASK_MODES or mode == LOSS_MASK_ALL:
        raise ValueError(f"check_loss_spans: mode {mode!r} is one of {LOSS_MASK_MODES[1:]}")
    union = isinstance(shards, ShardUnion)
    parts = shards.parts if union else [shards]
    names = [str(d) for d in (shards.directories if union else [shards.directory])]
    span_mode = mode in LOSS_SPAN_KEEP
    if span_mode and not any(p.has_loss_spans for p in parts):
        raise ValueError(f"data.loss_mask {mode!r} reads the loss-span classes ({LOSS_SPANS_FILE}), and no shard set has the "
                         f"file: {names}")
    out = []
    for p, name in zip(parts, names):
        spans = p.has_loss_spans and span_mode
        if not spans and span_mode:
            out.append(None)  # a part without the file: class 0 everywhere, its flags not read by a span mode
            continue
        meta = None
        if spans:
            meta = p.meta.get("loss_spans")
            if not isinstance(meta, dict):
                raise ValueError(f"{name}: {LOSS_SPANS_FILE} without the 'loss_spans' block in meta.json")
            if meta.get("version") != LOSS_SPANS_VERSION or meta.get("classes") != LOSS_SPAN_CLASSES:
                raise ValueError(f"{name}: meta.json loss_spans is version {meta.get('version')!r} with classes "
                                 f"{meta.get('classes')!r}; this code reads version {LOSS_SPANS_VERSION} with {LOSS_SPAN_CLASSES}")
            size = (p.directory / LOSS_SPANS_FILE).stat().st_size
            if size != p.n_tokens:
                raise ValueError(f"{name}: {LOSS_SPANS_FILE} holds {size} bytes for {p.n_tokens} tokens (one byte a token)")
        counts = np.zeros(256, dtype=np.int64)
        digest = hashlib.blake2b(digest_size=16)  # the span file's bytes (its identity in the data identity)
        for a in range(0, p.n_tokens, LOSS_CHECK_CHUNK):
            b = min(p.n_tokens, a + LOSS_CHECK_CHUNK)
            gen = np.asarray(p.generated[a:b])
            if int(gen.max()) > 1:
                i = a + int(np.argmax(gen > 1))
                raise ValueError(f"{name}: generated.bin holds {int(gen[i - a])} at token {i} (document "
                                 f"{_doc_of(p.doc_starts, i)}): it must be 0/1 when a loss mask reads the set")
            if not spans:
                continue
            sp = np.ascontiguousarray(p.loss_spans[a:b])
            counts += np.bincount(sp, minlength=256)
            digest.update(sp.tobytes())
            if int(sp.max()) > 3:
                i = a + int(np.argmax(sp > 3))
                raise ValueError(f"{name}: {LOSS_SPANS_FILE} holds the reserved value {int(sp[i - a])} at token {i} "
                                 f"(document {_doc_of(p.doc_starts, i)}); version 1 has the classes 0..3")
            on_gen = (sp > 0) & (gen > 0)
            if bool(on_gen.any()):
                i = a + int(np.argmax(on_gen))
                raise ValueError(f"{name}: class {int(sp[i - a])} on a generated token at token {i} (document "
                                 f"{_doc_of(p.doc_starts, i)}): no class above 0 is on a generated token")
            inner = (sp == 1) | (sp == 2)
            if bool(inner.any()):
                outside = inner & ~_chat_of_tokens(p.doc_starts, p.doc_chat, a, b)
                if bool(outside.any()):
                    i = a + int(np.argmax(outside))
                    raise ValueError(f"{name}: class {int(sp[i - a])} at token {i} of document {_doc_of(p.doc_starts, i)}, "
                                     "which is not a chat document: classes 1 and 2 are tool-output content")
        if not spans:
            out.append(None)
            continue
        have = {str(c): int(counts[c]) for c in range(4)}
        if "class_tokens" in meta and {str(k): int(v) for k, v in meta["class_tokens"].items()} != have:
            raise ValueError(f"{name}: the class counts of {LOSS_SPANS_FILE} are {have}, meta.json says {meta['class_tokens']}")
        out.append({"version": meta["version"], "head": meta.get("head"), "tail": meta.get("tail"), "class_tokens": have,
                    "blake2b": digest.hexdigest()})
    return {"mode": mode, "parts": out}


def open_shards(shard_dir: str | Path, extra_dirs=(), order: str = "permute") -> "ShardSet | ShardUnion":
    """The training data of DataConfig shard_dir and extra_shard_dirs: ShardSet(shard_dir) with no extra set (every run
    before the key, the same object), else the ShardUnion of shard_dir and the extra sets in that order, read in `order`
    (DataConfig.union_order: "permute", the default, or "sets_in_order")."""
    if not extra_dirs:
        if order != UNION_ORDER_PERMUTE:
            raise ValueError(f"data.union_order {order!r} orders the sets of a union; this run reads one set (data.extra_shard_dirs is empty)")
        return ShardSet(shard_dir)
    return ShardUnion([shard_dir, *extra_dirs], order=order)
