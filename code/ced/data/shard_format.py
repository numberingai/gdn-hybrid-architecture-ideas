UNION_FINGERPRINT_TAG = b"ced shard union v1\n"
# The order a union's first epoch is read in (DataConfig.union_order; ShardPacker._epoch). "permute": one permutation over every
# document of every set (the loader as built, 2026-10-15; its fingerprint is the one of before). "sets_in_order": the first set in
# its own epoch-0 permutation (the one a ShardPacker over that set alone draws, token for token), then the next set in a permutation
# of its own, and so on: no document is read twice before every set has been read once, and a run that trained on the first set
# alone can go on in the union where it stopped (long-data, 2026-10-30; section 12). Later epochs are one permutation over every
# document in both orders. The order enters the fingerprint when it is not "permute".
UNION_ORDER_PERMUTE, UNION_ORDER_SETS = "permute", "sets_in_order"
UNION_ORDERS = (UNION_ORDER_PERMUTE, UNION_ORDER_SETS)
UNION_ORDER_TAGS = {UNION_ORDER_SETS: b"order sets_in_order v1\n"}


class ConcatArray:
    """Read-only 1-D concatenation of arrays (the parts' memmaps), without a copy of the whole. Read by slices (step 1)
    or single integers: a slice inside one part is that part's slice; a slice across parts is the concatenation of
    the pieces. Every value comes back as `dtype` (np.result_type of the parts' dtypes, so a uint16 part next to a
    uint32 part reads as uint32, the same ids). Other indexing, and turning the whole into an array (np.asarray), is
    refused: the union of the item-6 sets is about 17.6B tokens."""

    def __init__(self, parts: list, dtype=None):
        self.parts = list(parts)
        self.dtype = np.dtype(dtype if dtype is not None else np.result_type(*[p.dtype for p in self.parts]))
        bounds = [0]
        for p in self.parts:
            bounds.append(bounds[-1] + len(p))
        self.bounds = bounds  # Python ints: part k holds [bounds[k], bounds[k + 1])
        self.shape = (bounds[-1],)

    def __len__(self) -> int:
        return self.bounds[-1]

    def __array__(self, *args, **kwargs):
        raise TypeError("ConcatArray is read by slices; it is never turned into one array as a whole")

    def _part(self, i: int) -> int:
        import bisect

        return bisect.bisect_right(self.bounds, i) - 1

    def __getitem__(self, key):
        n = len(self)
        if isinstance(key, (int, np.integer)):
            i = int(key) + (n if int(key) < 0 else 0)
            if not 0 <= i < n:
                raise IndexError(f"index {int(key)} out of range for length {n}")
            k = self._part(i)
            return self.dtype.type(self.parts[k][i - self.bounds[k]])
        if not isinstance(key, slice):
            raise TypeError(f"ConcatArray is read by slices or integers, not {type(key).__name__}")
        start, stop, step = key.indices(n)
        if step != 1:
            raise TypeError("ConcatArray is read by slices of step 1")
        if stop <= start:
            return np.empty(0, dtype=self.dtype)
        pieces, k = [], self._part(start)
        while start < stop:
            lo, hi = self.bounds[k], self.bounds[k + 1]
            end = min(stop, hi)
            pieces.append(np.asarray(self.parts[k][start - lo : end - lo]).astype(self.dtype, copy=False))
            start, k = end, k + 1
        return pieces[0] if len(pieces) == 1 else np.concatenate(pieces)


class ZerosArray:
    """A read-only 1-D array of n zeros (a ConcatArray part): the loss-span classes of a union part without loss_spans.bin,
    class 0 at every token. Read by slices of step 1 or by integers, as ConcatArray reads its parts."""

    def __init__(self, n: int, dtype=np.uint8):
        self.n, self.dtype = int(n), np.dtype(dtype)
        self.shape = (self.n,)

    def __len__(self) -> int:
        return self.n

    def __getitem__(self, key):
        if isinstance(key, (int, np.integer)):
            if not -self.n <= int(key) < self.n:
                raise IndexError(f"index {int(key)} out of range for length {self.n}")
            return self.dtype.type(0)
        start, stop, step = key.indices(self.n)
        assert step == 1, "ZerosArray is read by slices of step 1"
        return np.zeros(max(0, stop - start), dtype=self.dtype)


class ShardUnion:
    """Two or more shard sets read as ONE set (DataConfig.extra_shard_dirs).

    The union's documents are the first set's documents in their stored order, then the second set's, and so on:
    document i of the union is document i of set 0 for i < n_0, document i - n_0 of set 1 after that. Every field a
    reader of ShardSet uses has the same meaning here: tokens, generated and byte_lens are ConcatArray views of the
    parts' files (no copy); doc_starts and doc_chat are the concatenated indexes (doc_starts shifted by the tokens of
    the sets before); doc_source maps every part's source names onto one list (meta["sources"]: the first set's names,
    then names new in later sets) and is None unless every part has one. So a ShardPacker over the union is, bit for
    bit, a ShardPacker over ONE set written with the concatenated document lists (tests/test_two_set_loader.py).

    ORDER (long-data, 2026-10-30; DataConfig.union_order; UNION_ORDERS). "permute" (the default) is what the paragraph above describes:
    the packer's first epoch is one permutation over every document. "sets_in_order" reads the first epoch set by set: the first
    set in the permutation a packer over it alone draws (token for token, so a run trained on that set alone goes on in the union
    where it stopped), then the next set in a permutation of its own; later epochs are one permutation over every document
    (ShardPacker._sets_in_order_layout). The order is part of the fingerprint unless it is "permute" (whose fingerprint is the one
    of before), and `extends_fingerprint` names the first set for the trainer's stage check.

    Refused: fewer than two sets; one directory twice; two sets with the same fingerprint (the same data at two paths:
    each of its documents would be read twice an epoch); sets whose meta.json names different tokenizers
    (tokenizer_sha256, absent counting as a value). Sets with different token dtypes are read as the wider dtype
    (uint16 and uint32: uint32), the same ids.

    The fingerprint (the data identity a checkpoint records; Trainer.data_state) is blake2b-128 over a fixed tag and
    the parts' own fingerprints (ShardSet.fingerprint) in order: it covers each set exactly as that set's own
    fingerprint does, and the order of the sets. Another pair, the same pair in the other order, or one set alone has
    another fingerprint, so a resume refuses it and a stage sees new data. (A merged copy of the sets written to one
    directory would have ShardSet's fingerprint, another value: none exists or is planned.)"""

    def __init__(self, directories, order: str = UNION_ORDER_PERMUTE):
        if order not in UNION_ORDERS:
            raise ValueError(f"a shard union's order is one of {UNION_ORDERS}, not {order!r}")
        self.order = order
        directories = [str(d) for d in directories]
        if len(directories) < 2:
            raise ValueError(f"a shard union reads two or more sets, not {directories!r} (one set: ShardSet)")
        resolved = [str(Path(d).resolve()) for d in directories]
        if len(set(resolved)) != len(resolved):
            raise ValueError(f"shard sets {directories!r}: one directory is named twice (its documents would be read "
                             "twice an epoch)")
        parts = [ShardSet(d) for d in directories]
        fingerprints = [p.fingerprint() for p in parts]
        if len(set(fingerprints)) != len(fingerprints):
            raise ValueError(f"shard sets {directories!r}: two sets have the same fingerprint (the same data at two "
                             f"paths: {fingerprints}); each document would be read twice an epoch")
        tokenizers = [p.meta.get("tokenizer_sha256") for p in parts]
        if len(set(tokenizers)) != 1:
            raise ValueError(f"shard sets {directories!r} were built with different tokenizers (meta.json "
                             f"tokenizer_sha256 {tokenizers}): a union of them is not one token stream")
        self.parts = parts
        self.directories = directories
        self.part_fingerprints = fingerprints
        offsets = np.cumsum([0] + [p.n_tokens for p in parts])
        self.doc_starts = np.concatenate([parts[0].doc_starts[:1]] + [p.doc_starts[1:] + off for p, off in
                                                                      zip(parts, offsets)]).astype(np.int64)
        self.doc_chat = np.concatenate([p.doc_chat for p in parts])
        self.n_docs = len(self.doc_chat)
        self.n_tokens = int(self.doc_starts[-1])
        self.tokens = ConcatArray([p.tokens for p in parts])
        self.token_dtype = {np.dtype(v): k for k, v in TOKEN_DTYPES.items()}[self.tokens.dtype]
        self.generated = ConcatArray([p.generated for p in parts])
        self.byte_lens = ConcatArray([p.byte_lens for p in parts]) if all(p.byte_lens is not None for p in parts) else None
        self.doc_source, names = None, None
        if all(p.doc_source is not None and p.meta.get("sources") for p in parts):
            names = []
            for p in parts:
                names += [n for n in p.meta["sources"] if n not in names]
            assert len(names) <= np.iinfo(np.uint16).max + 1
            self.doc_source = np.concatenate([
                np.asarray([names.index(n) for n in p.meta["sources"]], dtype=np.uint16)[p.doc_source] for p in parts])
        self.directory = None  # no one directory: see self.directories
        assert len(self.doc_starts) == self.n_docs + 1 and len(self.tokens) == self.n_tokens == len(self.generated)
        self.meta = {"n_docs": self.n_docs, "n_tokens": self.n_tokens, "token_dtype": self.token_dtype,
                     "tokenizer_sha256": tokenizers[0], "union": self.describe()["parts"]}
        if names is not None:
            self.meta["sources"] = names
        if tokenizers[0] is None:
            del self.meta["tokenizer_sha256"]
        h = hashlib.blake2b(digest_size=16)
        h.update(UNION_FINGERPRINT_TAG)
        if order != UNION_ORDER_PERMUTE:  # the order is part of the data identity; "permute" hashes as it always did
            h.update(UNION_ORDER_TAGS[order])
        for f in fingerprints:
            h.update(f.encode() + b"\n")
        self._fingerprint = h.hexdigest()

    def fingerprint(self) -> str:
        """The union's data identity (class docstring): blake2b-128 over the tag and the parts' fingerprints."""
        return self._fingerprint

    @property
    def extends_fingerprint(self) -> str | None:
        """Order "sets_in_order": the fingerprint of the first set, whose own first epoch (a ShardPacker over it alone) is, token
        for token, the beginning of this union's first epoch (ShardPacker._sets_in_order_layout); a checkpoint trained on that set
        alone can be continued on this union without a stream restart (ced.train.trainer.stage_data_relation, relation
        "extends"). None for order "permute": its first epoch is one permutation over every document, which is nobody's prefix."""
        return self.part_fingerprints[0] if self.order == UNION_ORDER_SETS else None

    @property
    def has_loss_spans(self) -> bool:
        """Whether any part has loss_spans.bin. Nothing is opened."""
        return any(p.has_loss_spans for p in self.parts)

    @property
    def loss_spans(self):
        """The union's loss-span classes: a ConcatArray of the parts' files, zeros (class 0) for a part without one; None
        when no part has one. Opened at the first read only (ShardSet.loss_spans)."""
        if "_loss_spans" not in self.__dict__:
            self._loss_spans = (ConcatArray([p.loss_spans if p.loss_spans is not None else ZerosArray(p.n_tokens)
                                             for p in self.parts], dtype=np.uint8) if self.has_loss_spans else None)
        return self._loss_spans

    def describe(self) -> dict:
        """The parts, for the run's start record: directory, documents, tokens, token dtype, fingerprint and first union document of each; the union's totals."""
        first, parts = 0, []
        for d, p, f in zip(self.directories, self.parts, self.part_fingerprints):
            parts.append({"directory": d, "n_docs": p.n_docs, "n_tokens": p.n_tokens, "token_dtype": p.token_dtype,
                          "fingerprint": f, "first_doc": first})
            first += p.n_docs
        out = {"parts": parts, "n_docs": sum(p.n_docs for p in self.parts),
               "n_tokens": sum(p.n_tokens for p in self.parts)}
        if self.order != UNION_ORDER_PERMUTE:  # absent for "permute": the start records of before are unchanged
            out["order"] = self.order
        return out


