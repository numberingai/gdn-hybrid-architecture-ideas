@dataclass
class RoleDoc(TokenizedDoc):
    """A chat document. `assistant[i]` is 1 where token i is generated by the assistant: message
    content and its end-of-turn token, not the role header, which the harness inserts (the same
    convention as the `generated` flags of tools/tokenize_to_shards.py)."""

    assistant: list[int]
    # Optional: the token classes of the document's tokens (ced/data/token_classes.py: 0 loss, 1 tool-output content middle,
    # 2 its head and tail, 3 always masked), one per token. Read by build_whole_role_rows only, which then gives the rows a
    # `target_class`; None: the rows carry none and nothing changes.
    token_class: list[int] | None = None

    def __post_init__(self):
        super().__post_init__()
        assert len(self.assistant) == len(self.ids)
        assert self.token_class is None or len(self.token_class) == len(self.ids)


@dataclass(frozen=True)
class SpanParams:
    """Span-length distribution for the eval masks. The defaults are the pretraining spans decided
    on 2026-10-03 (log-normal, median 230, sigma 1.16, truncated to [16, min(C, 4096)])."""

    distribution: str = "lognormal"
    median: float = 230.0
    sigma: float = 1.16
    span_min: int = 16
    span_max: int = 4096

    @classmethod
    def from_data_config(cls, cfg: DataConfig) -> "SpanParams":
        """The spans a run was trained with, so the eval mask has the training distribution."""
        return cls(cfg.span_distribution, cfg.span_median, cfg.span_sigma, cfg.span_min, cfg.span_max)


@dataclass
class EvalRows:
    tokens: torch.Tensor  # (N, L) long, inputs
    targets: torch.Tensor  # (N, L) long, next tokens
    target_valid: torch.Tensor  # (N, L) bool; False across document boundaries and in padding
    target_bytes: torch.Tensor  # (N, L) long; UTF-8 bytes covered by each target token
    doc_ids: torch.Tensor  # (N, L) long; increasing along each row, never reused
    dec_mask: torch.Tensor  # (N, L) bool; decoder positions
    capacity: int  # decoder slots Looped-CED gets at eval; never fewer than a row's decoder positions
    kind: str  # "spans" or "roles"
    # Optional metadata, not part of the fingerprint (neither changes which positions are scored):
    # - doc_group: (n_docs + 1,) cluster id per document index (e.g. an agent document's
    #   environment); rows are clustered by their dominant document's group (`row_clusters`);
    # - special_ids: the vocabulary ids of the special tokens, so `evaluate` also reports their
    #   nats and bytes per row (bpb with special tokens counted as 0 bytes).
    doc_group: torch.Tensor | None = None
    special_ids: torch.Tensor | None = None
    # - target_class: (N, L) uint8, the token class (ced/data/token_classes.py) of each row's target token, for the chat strata of
    #   eval sets built with token classes (the held-out set builder is not part of this release). `evaluate` then also sums nats, bytes
    #   and tokens per class (SpanEval.seg_class_*). It is per row, so slicing a set slices it. None: no class sums.
    target_class: torch.Tensor | None = None

    def __len__(self) -> int:
        return self.tokens.shape[0]

    @property
    def seq_len(self) -> int:
        return self.tokens.shape[1]

    def _with(self, fields: dict, target_class: torch.Tensor | None = None) -> "EvalRows":
        """New rows from `fields` (the per-row tensors, cut the same way); doc_group and special_ids index documents and the
        vocabulary and are kept as they are; target_class is per row and is the caller's to cut (None: the new rows have none)."""
        return EvalRows(**fields, capacity=self.capacity, kind=self.kind, doc_group=self.doc_group,
                        special_ids=self.special_ids, target_class=target_class)

    def __getitem__(self, index: slice) -> "EvalRows":
        """A contiguous block of rows (for batching or `--max-rows`)."""
        assert isinstance(index, slice)
        return self._with({f: getattr(self, f)[index] for f in self._FIELDS},
                          None if self.target_class is None else self.target_class[index])

    _FIELDS = ("tokens", "targets", "target_valid", "target_bytes", "doc_ids", "dec_mask")
    _OPTIONAL = ("doc_group", "special_ids", "target_class")

    def save(self, path) -> None:
        extra = {k: getattr(self, k) for k in self._OPTIONAL if getattr(self, k) is not None}
        torch.save({**{f: getattr(self, f) for f in self._FIELDS}, "capacity": self.capacity, "kind": self.kind,
                    "fingerprint": self.fingerprint(), **extra}, path)

    @classmethod
    def load(cls, path) -> "EvalRows":
        data = torch.load(path, weights_only=True)
        rows = cls(**{f: data[f] for f in cls._FIELDS}, capacity=int(data["capacity"]), kind=data["kind"],
                   **{k: data.get(k) for k in cls._OPTIONAL})
        assert rows.fingerprint() == data["fingerprint"], f"{path}: contents do not match the saved fingerprint"
        assert rows.target_class is None or (rows.target_class.shape == rows.tokens.shape and rows.target_class.dtype == torch.uint8
                                             and int(rows.target_class.max()) <= 3), f"{path}: target_class is not a uint8 (N, L) array of 0..3"
        return rows

    def fingerprint(self) -> str:
        """A hash of everything that defines the scored positions. Two evaluations are paired only
        if their fingerprints agree."""
        h = hashlib.blake2b(digest_size=16)
        h.update(f"{self.kind}:{self.capacity}:{tuple(self.tokens.shape)}".encode())
        for t in (self.tokens, self.targets, self.target_valid, self.target_bytes, self.doc_ids, self.dec_mask):
            h.update(t.detach().to("cpu", torch.long).contiguous().numpy().tobytes())
        return h.hexdigest()


def _pack(docs: list[TokenizedDoc], seq_len: int) -> dict[str, torch.Tensor]:
    """Concatenate the documents and cut the stream into rows of seq_len + 1 tokens that overlap by
    one. Returns the shifted (N, L) views, plus whether each target is an assistant token."""
    L = seq_len
    assert L >= 1
    ids, nbytes, assistant, doc = [], [], [], []
    for i, d in enumerate(docs):
        n = len(d.ids)
        if n == 0:
            continue
        ids.append(torch.tensor(d.ids, dtype=torch.long))
        nbytes.append(torch.tensor(d.byte_lens, dtype=torch.long))
        flags = d.assistant if isinstance(d, RoleDoc) else [0] * n
        assistant.append(torch.tensor(flags, dtype=torch.bool))
        doc.append(torch.full((n,), i, dtype=torch.long))  # the index in `docs`: increasing
    if not ids or sum(len(x) for x in ids) < 2:
        raise ValueError("the documents hold no target to score")

    stream = {"ids": torch.cat(ids), "bytes": torch.cat(nbytes), "assistant": torch.cat(assistant), "doc": torch.cat(doc)}
    n = stream["ids"].numel()
    n_rows = math.ceil((n - 1) / L)
    pad = n_rows * L + 1 - n
    # Padding: one extra document (a fresh, larger id) of token 0, covering no bytes. Its targets are
    # marked invalid explicitly, since pad -> pad would otherwise look like an in-document target.
    stream["ids"] = torch.cat([stream["ids"], torch.zeros(pad, dtype=torch.long)])
    stream["bytes"] = torch.cat([stream["bytes"], torch.zeros(pad, dtype=torch.long)])
    stream["assistant"] = torch.cat([stream["assistant"], torch.zeros(pad, dtype=torch.bool)])
    stream["doc"] = torch.cat([stream["doc"], torch.full((pad,), len(docs), dtype=torch.long)])
    real = torch.arange(n_rows * L + 1) < n

    index = torch.arange(n_rows)[:, None] * L + torch.arange(L + 1)[None, :]  # (N, L + 1)
    ids_r, bytes_r, asst_r, doc_r, real_r = (x[index] for x in (stream["ids"], stream["bytes"], stream["assistant"], stream["doc"], real))
    same_doc = doc_r[:, 1:] == doc_r[:, :-1]
    return {
        "tokens": ids_r[:, :-1],
        "targets": ids_r[:, 1:],
        "target_valid": same_doc & real_r[:, 1:],
        "target_bytes": bytes_r[:, 1:],
        "doc_ids": doc_r[:, :-1],
        "target_assistant": asst_r[:, 1:],
    }


def build_eval_rows(
    docs: list[TokenizedDoc],
    seq_len: int,
    capacity: int,
    spans: SpanParams = SpanParams(),
    seed: int = 0,
) -> EvalRows:
    """Rows with exactly `capacity` decoder positions each, in fixed-seed spans.

    The mask of row i depends only on (seed, i, seq_len, capacity, spans), never on the tokens or
    the document boundaries, exactly like the training sampler: a mask that depended on where a
    document ends would tell earlier positions about the future through the kind of KV they offer.
    To match the training distribution of non-chat rows, use capacity = round(span_fraction * L)
    (what `ced.train.shards.ShardPacker` places) and the run's own `SpanParams.from_data_config`.

    Spans may cover invalid targets (document ends, padding); those positions run the decoder but
    are not scored, so a row can score slightly fewer than `capacity` targets.
    """
    assert 0 <= capacity <= seq_len
    rows = _pack(docs, seq_len)
    masks = [
        sample_spans(
            seq_len, capacity, counter_generator(seed, i, stream=EVAL_SPAN_STREAM),
            distribution=spans.distribution, median=spans.median, sigma=spans.sigma,
            span_min=spans.span_min, span_max=spans.span_max,
        )
        for i in range(rows["tokens"].shape[0])
    ]
    del rows["target_assistant"]
    return EvalRows(**rows, dec_mask=torch.stack(masks), capacity=capacity, kind="spans")


def build_role_eval_rows(docs: list[RoleDoc], seq_len: int) -> EvalRows:
    """Rows of chat trajectories with decoder positions by role.

    Position t is a decoder position iff the token at t + 1 is an assistant token of the same
    document (as in `ced.train.shards.ShardPacker`): from the last token of the assistant header
    through the token before the end-of-turn token. The count per row varies, so the capacity is
    L: nothing is dropped, every assistant token is scored by the decoder head.
    """
    assert all(isinstance(d, RoleDoc) for d in docs), "role rows need RoleDoc documents"
    rows = _pack(docs, seq_len)
    dec_mask = rows.pop("target_assistant") & rows["target_valid"]
    return EvalRows(**rows, dec_mask=dec_mask, capacity=seq_len, kind="roles")


def build_whole_role_rows(docs: list[RoleDoc], seq_len: int, max_scored: int | None = None) -> EvalRows:
    """Role rows in which no document is cut by a row boundary: a row holds L + 1 stream tokens,
    filled first-fit with whole documents in order; when the next document does not fit, the rest
    of the row is an inert padding document (id len(docs), token 0, invalid targets, never scored).
    Used for agent eval pieces (each at most one row, like the training packer's chat documents)
    and for multiple choice. Document ids are the indices in `docs`; decoder positions are those
    whose next token is an assistant token of the same document; capacity L.
    max_scored: a row also ends before a document whose decoder positions would take the row's
    past it (so a model whose decoder keeps the first C positions of a row loses none; a single
    document with more is a row of its own)."""
    L = seq_len
    rows, cur = [], []
    used = scored = 0
    for i, d in enumerate(docs):
        n = len(d.ids)
        k = int(sum(d.assistant))  # its decoder positions: each assistant token is a target in the document
        assert n <= L + 1, f"document {i} has {n} tokens, more than a row ({L + 1})"
        if cur and (used + n > L + 1 or (max_scored is not None and scored + k > max_scored)):
            rows.append(cur)
            cur, used, scored = [], 0, 0
        cur.append(i)
        used += n
        scored += k
    if cur:
        rows.append(cur)
    fields = {k: [] for k in ("tokens", "targets", "target_valid", "target_bytes", "doc_ids", "dec_mask")}
    with_class = [getattr(d, "token_class", None) is not None for d in docs]  # duck-typed documents have none
    if any(with_class) and not all(with_class):
        raise ValueError("token classes on some documents and not on others: the rows would have classes for part of a set")
    classes = []  # per row, the class of each target token (padding: 0), when the documents carry classes
    for row in rows:
        ids, nbytes, asst, doc, cls = [], [], [], [], []
        for i in row:
            d = docs[i]
            ids += d.ids
            nbytes += d.byte_lens
            asst += d.assistant
            doc += [i] * len(d.ids)
            if with_class[i]:
                cls += d.token_class
        pad = L + 1 - len(ids)
        ids += [0] * pad
        nbytes += [0] * pad
        asst += [0] * pad
        doc += [len(docs)] * pad
        real = torch.arange(L + 1) < (L + 1 - pad)
        ids_t, bytes_t, asst_t, doc_t = (torch.tensor(x) for x in (ids, nbytes, asst, doc))
        valid = (doc_t[1:] == doc_t[:-1]) & real[1:]
        fields["tokens"].append(ids_t[:-1])
        fields["targets"].append(ids_t[1:])
        fields["target_valid"].append(valid)
        fields["target_bytes"].append(bytes_t[1:])
        fields["doc_ids"].append(doc_t[:-1])
        fields["dec_mask"].append(asst_t[1:].bool() & valid)
        if all(with_class) and docs:
            cls += [0] * pad
            classes.append(torch.tensor(cls, dtype=torch.uint8)[1:])
    out = EvalRows(**{k: torch.stack(v) for k, v in fields.items()}, capacity=L, kind="roles")
    if classes:
        # the class of each scored target; 0 where the target is not valid (a document's end, whose next token is another
        # document's first, and the padding)
        out.target_class = torch.where(out.target_valid, torch.stack(classes), torch.zeros((), dtype=torch.uint8))
        assert int(out.target_class.max()) <= 3, "a token class above 3 (the loss-span classes are 0..3)"
    return out


def drop_unscored_rows(rows: EvalRows) -> EvalRows:
    """The rows with at least one scored target (valid and at a decoder position). A row that
    scores nothing costs a forward pass and contributes nothing (build time only)."""
    keep = (rows.target_valid & rows.dec_mask).any(dim=1)
    return rows._with({f: getattr(rows, f)[keep] for f in EvalRows._FIELDS},
                      None if rows.target_class is None else rows.target_class[keep])


def row_clusters(rows: EvalRows) -> torch.Tensor:
    """(N,) long: each row's cluster, for standard errors that allow for rows of the same document
    (every row boundary splits a document) or the same environment. A row's dominant document is
    the one with the most scored bytes (most tokens when nothing is scored); the cluster is that
    document's `doc_group`, or the document itself when the rows carry no groups."""
    scored = (rows.target_valid & rows.dec_mask).long() * rows.target_bytes
    out = []
    for r in range(len(rows)):
        docs, inverse = torch.unique_consecutive(rows.doc_ids[r], return_inverse=True)
        weight = torch.zeros(len(docs), dtype=torch.long).index_add_(0, inverse, scored[r])
        if int(weight.sum()) == 0:
            weight = torch.bincount(inverse, minlength=len(docs))
        out.append(int(docs[int(weight.argmax())]))
    dominant = torch.tensor(out, dtype=torch.long)
    return rows.doc_group[dominant] if rows.doc_group is not None else dominant


