@dataclass
class SpanEval:
    """Scores of one model on one set of rows. Per-row sums are kept for paired comparisons."""

    dec_bpb: float
    ctx_bpb: float
    all_bpb: float
    n_dec_tokens: int
    n_ctx_tokens: int
    n_dec_bytes: int
    n_ctx_bytes: int
    row_dec_nats: torch.Tensor  # (N,) float64: sum of CE at scored decoder positions
    row_ctx_nats: torch.Tensor  # (N,) float64: sum of CE at scored context positions
    row_dec_bytes: torch.Tensor  # (N,) long
    row_ctx_bytes: torch.Tensor  # (N,) long
    row_dec_tokens: torch.Tensor  # (N,) long
    row_ctx_tokens: torch.Tensor  # (N,) long
    arch: str
    T: int | None  # loop count used (None for a model without a loop)
    rows_fingerprint: str
    row_cluster: torch.Tensor | None = None  # (N,) long, `row_clusters` of the rows: for clustered SEs
    # The reference-vs-fused head comparison of evaluate(fused_check=True), or None.
    fused_check: dict | None = None
    # The part of the row sums at special-token targets (when the rows carry special_ids), so bpb can
    # also be reported with special tokens counted as 0 bytes. The string-length convention is primary.
    row_dec_special_nats: torch.Tensor | None = None
    row_dec_special_bytes: torch.Tensor | None = None
    row_ctx_special_nats: torch.Tensor | None = None
    row_ctx_special_bytes: torch.Tensor | None = None
    # The same sums per (row, document) segment: a row holds pieces of several documents, often of
    # different environments, so standard errors are clustered by each segment's own group
    # (seg_group: the document's `doc_group`, else the document), not by the row's dominant
    # document. Segments without a valid target are left out.
    seg_row: torch.Tensor | None = None
    seg_doc: torch.Tensor | None = None
    seg_group: torch.Tensor | None = None
    seg_dec_nats: torch.Tensor | None = None
    seg_ctx_nats: torch.Tensor | None = None
    seg_dec_bytes: torch.Tensor | None = None
    seg_ctx_bytes: torch.Tensor | None = None
    seg_dec_special_nats: torch.Tensor | None = None
    seg_ctx_special_nats: torch.Tensor | None = None
    seg_dec_special_bytes: torch.Tensor | None = None
    seg_ctx_special_bytes: torch.Tensor | None = None
    # CED v2 and the second-pass control (the decoder at every scored position; see the module
    # docstring): where the decoder ran ("rows": the rows' decoder mask, Looped-CED; "every": every
    # valid target; None: no decoder), and the diagnostic heads at the same positions: the aux head
    # ("aux") and CED v2's loop-1 readout ("loop1"), as bpb and per-row nats at the decoder ("dec")
    # and context ("ctx") positions of the rows. Bytes are row_dec_bytes / row_ctx_bytes.
    decoder_at: str | None = None
    aux_bpb: float | None = None
    aux_all_bpb: float | None = None
    loop1_bpb: float | None = None
    loop1_all_bpb: float | None = None
    row_aux_dec_nats: torch.Tensor | None = None
    row_aux_ctx_nats: torch.Tensor | None = None
    row_loop1_dec_nats: torch.Tensor | None = None
    row_loop1_ctx_nats: torch.Tensor | None = None
    # Stage 3's restricted-regime comparisons (tools/analysis/auto/stage3_bpb.py). None in evaluations saved before
    # these fields existed.
    # - replay_window: W of decoder_at "rows_sinks_replay", or the last-turn window's name ("turn", "turn128":
    #   ced/eval/replay_window.py) (None in every other regime);
    # - row_decoder_slots: per row, the positions at which the decoder (pass 2) ran: the cost side of a regime
    #   (every valid target under "every"; the rows' decoder positions, plus sinks, plus replay positions in the
    #   restricted regimes; None for a model without a decoder);
    # - the part of the dec sums at span starts: the scored decoder positions whose previous position is not a scored
    #   decoder position of the same document (ced.train.positions.span_starts), i.e. the first token of each
    #   assistant turn of role rows and of each span of span rows: the position that has no decoder history of its
    #   own span. The rest of a row is row_dec_* minus these.
    replay_window: int | str | None = None
    row_decoder_slots: torch.Tensor | None = None
    row_start_nats: torch.Tensor | None = None
    row_start_bytes: torch.Tensor | None = None
    row_start_tokens: torch.Tensor | None = None
    # The per-segment sums by token class, when the rows carry `target_class` (the heldout-v1 chat strata built with classes):
    # (S, 4, 2) for the same S segments as seg_row, [segment, class 0..3, 0 decoder position / 1 context position]. The two cells of
    # a class add up to that class's share of seg_dec_* + seg_ctx_*; summed over the classes they give seg_dec_* and seg_ctx_*
    # (class 0 at decoder positions is the assistant tokens). None, and left out of to_dict, for rows without classes: a
    # result then has exactly the fields it had before.
    seg_class_nats: torch.Tensor | None = None
    seg_class_bytes: torch.Tensor | None = None
    seg_class_tokens: torch.Tensor | None = None

    def seg_sums(self, metric: str, special_bytes: bool = True) -> tuple[torch.Tensor, torch.Tensor] | None:
        """(nats, bytes) per segment, like `row_sums`; None if the evaluation has no segments (or
        for the diagnostic heads, which are kept per row only)."""
        if self.seg_group is None or metric not in ("dec", "ctx", "all"):
            return None
        if metric == "all":
            (a, b), (c, d) = self.seg_sums("dec", special_bytes), self.seg_sums("ctx", special_bytes)
            return a + c, b + d
        nats, nbytes = getattr(self, f"seg_{metric}_nats"), getattr(self, f"seg_{metric}_bytes")
        if not special_bytes:
            nbytes = nbytes - getattr(self, f"seg_{metric}_special_bytes")
        return nats, nbytes

    def row_sums(self, metric: str, special_bytes: bool = True) -> tuple[torch.Tensor, torch.Tensor]:
        """(nats, bytes) per row for "dec", "ctx" or "all", or a diagnostic head's at the same
        positions: "aux" / "aux_all" and "loop1" / "loop1_all" (the main head's bytes).
        special_bytes=False leaves the bytes of special-token targets out of the denominator (their
        nats stay in the numerator)."""
        if metric == "all":
            (a, b), (c, d) = self.row_sums("dec", special_bytes), self.row_sums("ctx", special_bytes)
            return a + c, b + d
        head, _, where = metric.partition("_")
        if head in ("aux", "loop1") and where in ("", "all"):
            if getattr(self, f"row_{head}_dec_nats") is None:
                raise ValueError(f"this evaluation has no {head} head")
            _, dec_bytes = self.row_sums("dec", special_bytes)
            if where == "":
                return getattr(self, f"row_{head}_dec_nats"), dec_bytes
            _, ctx_bytes = self.row_sums("ctx", special_bytes)
            return getattr(self, f"row_{head}_dec_nats") + getattr(self, f"row_{head}_ctx_nats"), dec_bytes + ctx_bytes
        if metric not in ("dec", "ctx"):
            raise ValueError(f"unknown metric {metric!r}")
        nats, nbytes = getattr(self, f"row_{metric}_nats"), getattr(self, f"row_{metric}_bytes")
        if not special_bytes:
            special = getattr(self, f"row_{metric}_special_bytes")
            assert special is not None, "these rows were scored without special_ids"
            nbytes = nbytes - special
        return nats, nbytes

    def bpb_without_special_bytes(self, metric: str = "dec") -> float:
        nats, nbytes = self.row_sums(metric, special_bytes=False)
        return bpb(nats.sum(), nbytes.sum())

    CLASS_FIELDS = ("seg_class_nats", "seg_class_bytes", "seg_class_tokens")  # left out of to_dict when None

    def to_dict(self) -> dict:
        out = {}
        for key, value in self.__dict__.items():
            if value is None and key in self.CLASS_FIELDS:
                continue  # rows without classes: the dict is what it was before the fields existed
            out[key] = value.tolist() if isinstance(value, torch.Tensor) else value
        return out

    @classmethod
    def from_dict(cls, data: dict) -> "SpanEval":
        data = dict(data)
        for key in ("row_dec_nats", "row_ctx_nats", "row_dec_special_nats", "row_ctx_special_nats",
                    "seg_dec_nats", "seg_ctx_nats", "seg_dec_special_nats", "seg_ctx_special_nats",
                    "row_aux_dec_nats", "row_aux_ctx_nats", "row_loop1_dec_nats", "row_loop1_ctx_nats", "row_start_nats",
                    "seg_class_nats"):
            if data.get(key) is not None:
                data[key] = torch.tensor(data[key], dtype=torch.float64)
        for key in ("row_dec_bytes", "row_ctx_bytes", "row_dec_tokens", "row_ctx_tokens", "row_cluster",
                    "row_dec_special_bytes", "row_ctx_special_bytes", "seg_row", "seg_doc", "seg_group",
                    "seg_dec_bytes", "seg_ctx_bytes", "seg_dec_special_bytes", "seg_ctx_special_bytes",
                    "row_decoder_slots", "row_start_bytes", "row_start_tokens", "seg_class_bytes", "seg_class_tokens"):
            if data.get(key) is not None:
                data[key] = torch.tensor(data[key], dtype=torch.long)
        return cls(**data)


def bpb(nats: float | torch.Tensor, n_bytes: int | torch.Tensor) -> float:
    n_bytes = float(n_bytes)
    return float(nats) / (LN2 * n_bytes) if n_bytes > 0 else float("nan")


def token_cross_entropy(logits: torch.Tensor, targets: torch.Tensor, chunk: int = 1024) -> torch.Tensor:
    """CE in nats per position, (B, L) float64, in chunks along L so that the temporaries of the
    log-sum-exp stay small at a 128k vocabulary. Computed in at least float32, as the loss is."""
    dtype = torch.promote_types(logits.dtype, torch.float32)
    pieces = []
    for a in range(0, logits.shape[1], chunk):
        x = logits[:, a : a + chunk].to(dtype)
        target_logit = x.gather(-1, targets[:, a : a + chunk, None]).squeeze(-1)
        pieces.append((torch.logsumexp(x, dim=-1) - target_logit).double())
    return torch.cat(pieces, dim=1)


def _device(model: nn.Module) -> torch.device:
    for tensor in (*model.parameters(), *model.buffers()):
        return tensor.device
    return torch.device("cpu")


def _scored_ce(model: nn.Module, inner: nn.Module, looped: bool, batch: "EvalRows", tokens, doc_ids, dec, targets,
               T, capacity: int, varlen: dict | None, fused_check: dict | None = None) -> torch.Tensor:
    """CE (B, L) float64 at every position, from the model's hidden states and the tied head in
    chunks (no full (B, L, V) logits): the decoder head at kept decoder positions, the aux / single
    head elsewhere. The same numbers as token_cross_entropy(model(...).logits, targets). This is the
    reference head (ced/train/chunked_loss.token_ce); the training's fused kernel is never used here.

    fused_check (a dict of running sums, or None): also score the same hidden states with the
    reference head and with the fused kernel (ced/train/fused_head.py), both with TF32 off, and
    accumulate how far apart they are at valid target positions (see `evaluate`).

    A model with a Copy-Paste head (model.cp_head; one head, the control): the CE of its next-token distribution
    (ced/model/cp_head.py head_token_ce: the mixture, or p_LM alone under score "lm"); the fused check then compares
    the training's mixture (fused_linear_cp_ce) with it."""
    from ced.model.capacity import gather_slots, scatter_slots
    from ced.model.cp_head import cp_head_of
    from ced.train.chunked_loss import token_ce

    if cp_head_of(inner) is not None:
        return _scored_ce_cp(model, inner, batch, tokens, doc_ids, dec, targets, T, varlen, fused_check)
    weight = inner.head_weight()
    if looped:
        # a model with a pass schedule (loop.unscored_passes) is told which of the run positions are scored: the
        # sinks and the replay positions of the restricted regimes are not
        sched = ({"scored": (batch.target_valid & batch.dec_mask).to(tokens.device)}
                 if getattr(inner, "schedule", None) is not None else {})
        out = model(tokens, doc_ids, dec, T=T, capacity=capacity, return_hidden=True, varlen=varlen, **sched)
        assert int(out.n_dropped.sum()) == 0, "decoder positions were dropped: raise rows.capacity"
        assert torch.equal(out.kept, dec), "the decoder head did not run at the rows' decoder positions"
        heads = [(out.hidden_aux, targets), (out.hidden_dec, gather_slots(targets, out.slot_index, fill=0))]
        combine = lambda a, b: scatter_slots(a, out.slot_index, b)  # noqa: E731
    else:  # one head at every position; T only for the control with a second pass (None otherwise: the call as before)
        out = model(tokens, doc_ids, dec, return_hidden=True, varlen=varlen, **({} if T is None else {"T": T}))
        heads = [(out.hidden_aux, targets)]
        combine = lambda a: a  # noqa: E731
    ce = combine(*[token_ce(h, weight, t)[0] for h, t in heads]).double()
    if fused_check is not None:
        _update_fused_check(fused_check, heads, combine, weight, batch, ce.device)
    return ce


def _scored_ce_cp(model: nn.Module, inner: nn.Module, batch: "EvalRows", tokens, doc_ids, dec, targets, T,
                  varlen: dict | None, fused_check: dict | None) -> torch.Tensor:
    """_scored_ce of a Copy-Paste model (one head at every position): CE (B, L) float64 of its next-token distribution
    (cp_head.head_token_ce). fused_check: the training's mixture (fused_linear_cp_ce, the score mode not read: the
    mixture) against the reference mixture (head_token_ce under "mixture"), both with TF32 off, as _update_fused_check
    does for the LM head."""
    from ced.model import cp_head as cp

    out = model(tokens, doc_ids, dec, return_hidden=True, varlen=varlen, **({} if T is None else {"T": T}))
    h = out.hidden_aux
    ce = cp.head_token_ce(inner, h, targets, tokens, doc_ids, pointer=out.cp_pointer)[0].double()
    if fused_check is not None:
        from ced.train.chunked_loss import token_lse_zy
        from ced.train.fused_head import fused_linear_cp_ce

        hp = fused_check.get("head_precision", "fp32")  # as in _update_fused_check
        old = torch.backends.cuda.matmul.allow_tf32
        torch.backends.cuda.matmul.allow_tf32 = False
        try:
            head, W = inner.cp_head, inner.lm_head_weight()
            with torch.autocast(h.device.type, enabled=False):
                ls, l1s, lp = cp.cp_terms(head, h, tokens, targets, doc_ids, pointer=out.cp_pointer)
                lse, z_y = token_lse_zy(h, W, targets, precision=hp)
                z_c = head.copy_logit(h)
                ref = (-cp.mixture_log_prob(lse, z_y, z_c, ls, l1s, lp)).double()
                flat = lambda x: x.reshape(-1)  # noqa: E731
                zeros = torch.zeros(targets.numel(), dtype=torch.float32, device=h.device)
                fused = fused_linear_cp_ce(h.reshape(-1, h.shape[-1]), W, flat(targets), zeros, zeros, flat(z_c),
                                           flat(ls), flat(l1s), flat(lp), chunk=fused_check.get("head_chunk"),
                                           precision=hp)[1].reshape(targets.shape).double()
        finally:
            torch.backends.cuda.matmul.allow_tf32 = old
        valid = batch.target_valid.to(h.device)
        on_dec = valid & batch.dec_mask.to(h.device)
        diff = torch.where(valid, (fused - ref).abs(), torch.zeros_like(ref))
        # nan_max: a NaN difference in a later batch stays NaN and fails within_criteria
        fused_check["max_abs_ce_diff"] = nan_max((fused_check["max_abs_ce_diff"], float(diff.max())))
        fused_check["dec_nats_ref"] += float(torch.where(on_dec, ref, torch.zeros_like(ref)).sum())
        fused_check["dec_nats_fused"] += float(torch.where(on_dec, fused, torch.zeros_like(ref)).sum())
        fused_check["positions"] += int(valid.sum())
    return ce


def _update_fused_check(check: dict, heads: list, combine, weight: torch.Tensor, batch: "EvalRows", device) -> None:
    """Score the same hidden states with the reference head and with the fused kernel
    (ced/train/fused_head.py), both with TF32 off, and accumulate how far apart they are at valid
    target positions, and both heads' nats at the rows' decoder positions (see `evaluate`). Both at the
    run's head precision (check["head_precision"], "fp32" when absent): the check is of the kernel the
    training ran, against the reference of the same function. The kernel at the run's chunk (check["head_chunk"], the
    fused head's default when absent; evaluate's head_chunk)."""
    from ced.train.chunked_loss import token_ce
    from ced.train.fused_head import fused_linear_ce

    hp = check.get("head_precision", "fp32")  # the run's TrainConfig.head_precision (evaluate's head_precision)
    chunk = check.get("head_chunk")  # the run's TrainConfig.head_chunk (evaluate's head_chunk); None: the default
    old = torch.backends.cuda.matmul.allow_tf32
    torch.backends.cuda.matmul.allow_tf32 = False
    try:
        ref = combine(*[token_ce(h, weight, t, precision=hp)[0] for h, t in heads]).double()
        fused = combine(*[fused_linear_ce(h, weight, t, torch.zeros_like(t, dtype=torch.float32),
                                          torch.zeros_like(t, dtype=torch.float32), chunk=chunk, precision=hp)[1]
                          for h, t in heads]).double()
    finally:
        torch.backends.cuda.matmul.allow_tf32 = old
    valid = batch.target_valid.to(device)
    on_dec = valid & batch.dec_mask.to(device)
    diff = torch.where(valid, (fused - ref).abs(), torch.zeros_like(ref))
    check["max_abs_ce_diff"] = nan_max((check["max_abs_ce_diff"], float(diff.max())))  # a NaN stays NaN
    check["dec_nats_ref"] += float(torch.where(on_dec, ref, torch.zeros_like(ref)).sum())
    check["dec_nats_fused"] += float(torch.where(on_dec, fused, torch.zeros_like(ref)).sum())
    check["positions"] += int(valid.sum())


def _every_position_ce(model: nn.Module, inner: nn.Module, batch: "EvalRows", tokens, doc_ids, valid, targets,
                       T: int | None, loop1: bool, varlen: dict | None, chunked_head: bool,
                       fused_check: dict | None = None) -> dict[str, torch.Tensor]:
    """CED v2 / second-pass scoring: the decoder (pass 2) runs at every valid target (dec_mask =
    valid, capacity L). Returns CE (B, L) float64 of the main head ("main"), of the aux head ("aux")
    and, with loop1, of CED v2's loop-1 readout through the final norm and head ("loop1"); positions
    without a valid target hold the aux head's value and are never scored.

    chunked_head: the reference head in chunks (ced/train/chunked_loss.token_ce); otherwise full
    logits (lm_head, token_cross_entropy). fused_check: as in _scored_ce, for the main head."""
    from ced.model.capacity import gather_slots, scatter_slots
    from ced.model.looped_ced import lm_head
    from ced.train.chunked_loss import token_ce

    weight = inner.head_weight()
    L = tokens.shape[1]
    kwargs = {} if T is None else {"T": T}
    if loop1:
        kwargs["return_drafts"] = True
    out = model(tokens, doc_ids, valid, capacity=L, return_hidden=True, varlen=varlen, **kwargs)
    assert int(out.n_dropped.sum()) == 0, "decoder positions were dropped"
    assert torch.equal(out.kept, valid), "the decoder did not run at every scored position"
    t_slots = gather_slots(targets, out.slot_index, fill=0)

    def head(h, t):
        if chunked_head:
            return token_ce(h, weight, t)[0].double()
        return token_cross_entropy(lm_head(h, weight), t)

    aux = head(out.hidden_aux, targets)
    scores = {"main": scatter_slots(aux, out.slot_index, head(out.hidden_dec, t_slots)), "aux": aux}
    if loop1:
        scores["loop1"] = scatter_slots(aux, out.slot_index, head(out.hidden_drafts[0], t_slots))
    if fused_check is not None:
        heads = [(out.hidden_aux, targets), (out.hidden_dec, t_slots)]
        _update_fused_check(fused_check, heads, lambda a, b: scatter_slots(a, out.slot_index, b), weight, batch,
                            aux.device)
    return scores


@torch.no_grad()
def evaluate(
    model: nn.Module,
    rows: EvalRows,
    T: int | None = None,
    batch_size: int = 8,
    chunked_head: bool = False,
    autocast_dtype: torch.dtype | None = None,
    fused_varlen: bool = False,
    fused_check: bool = False,
    decoder_at: str | None = None,
    replay_window: int | str = REPLAY_WINDOW,
    im_start: int | None = None,
    head_precision: str = "fp32",
    head_chunk: int | None = None,
) -> SpanEval:
    """Score `model` on `rows`.

    LoopedCED runs with the rows' decoder mask, capacity `rows.capacity` and loop count T (default:
    the config's t_eval); it must drop no decoder position, and its decoder head must run exactly
    at the rows' decoder positions. CED v2 and the second-pass control run the decoder (pass 2) at
    every valid target instead (capacity L; see the module docstring) and also report the aux head
    and, for CED v2 with T >= 2, the loop-1 readout at the same positions. The control (HybridLM) is
    called as model(tokens, doc_ids, dec_mask) and scored at the same positions by its single head;
    T is ignored for it and for the second-pass control. The control with a gated second pass through its top
    block (ced/model/control.py, "Two passes") is the exception: it runs T passes (default: its t_eval), pass 2 at
    every position as in training, and T = 1 scores its pass 1 alone.

    Memory note: by default the models return full (B, L, V) logits (Looped-CED materialises about
    three such tensors), so at L = 8192 and a 128k vocabulary one row is ~4 GB of float32 logits.
    chunked_head=True scores from hidden states with the head computed in chunks instead (the same
    numbers; tests/test_chunked_loss.py), which the GPU runs use.

    autocast_dtype: run the model body under torch.autocast with this dtype (the training
    precision); the head stays in float32 or wider either way. fused_varlen: pass host-computed
    segment boundaries so the fused GDN kernel runs (ced/train/varlen.py); otherwise the model's
    configured kernel falls back to its reference path.

    fused_check (with chunked_head): the scores always come from the reference head; this also
    scores the same hidden states with the training's fused kernel, both heads with TF32 off, and
    reports in SpanEval.fused_check the largest |CE difference| at a valid target position and both
    decoder bpbs. Criteria fixed before the first run: at most 1e-4 nats per position and 1e-6 in
    dec bpb; a larger difference is reported, never hidden.

    head_precision (the run's TrainConfig.head_precision; ced/train/head_precision.py): read by the fused check only, which then runs the fused kernel
    and the reference head both at it (the check is of the kernel the run trained with), records it in SpanEval.fused_check["head_precision"] when it
    is not "fp32", and keeps its criteria and its keys (dec_bpb_ref_fp32 and dec_bpb_fused_fp32 keep their names: "fp32" there means TF32 off; at
    "bf16" both are the bf16-operand head, as head_precision says). The scores never read it: they come from the reference head in float32.

    head_chunk (the run's TrainConfig.head_chunk when it is not the fused head's default, 2,048; ced/config.py): read by
    the fused check only, which then runs the fused kernel at that chunk and records it in
    SpanEval.fused_check["head_chunk"]; None (the default) runs the kernel at its default chunk, as before.

    decoder_at (CED v2 and the second-pass control only; None for every other arch): None or "every", the decoder
    (pass 2) at every valid target as above; "rows" (CED v2): the decoder at the rows' own decoder positions only
    (capacity rows.capacity, as Looped-CED runs), the restricted regime of stage 3: with decoder self-KV the other
    positions offer their memory entries and no decoder K/V, and dec_bpb is the main head there. Without self-KV it
    equals "every". "rows_sinks" (CED v2; "Sinks": the restricted regime keeps them): "rows" plus each document's
    first decoder.n_sinks positions in the row (document position < n_sinks), which run the decoder and write their
    own K/V so the local layers see their sinks as in training, and are not part of dec_bpb (positions outside the
    rows' decoder mask count in ctx_bpb, here from the main head at those positions); capacity L (one shape).
    "rows_sinks_replay" (CED v2; "replay window": the restricted regime is answers + sinks + replay window):
    "rows_sinks" plus the decoder at the min(replay_window, available) positions of the same document immediately
    before each run of consecutive scored positions of the rows (ced.train.positions.replay_positions; a span start is
    a scored position, valid and in the rows' decoder mask, whose previous position is not a scored position of the
    same document: each fixed-seed span of span rows, each assistant turn of role rows). The replay positions write
    decoder K/V and are not part of dec_bpb, so dec_bpb is at the same positions as "rows", "rows_sinks" and "every"
    and the regimes compare position for position; capacity L. The regime DataConfig.answer_replay_window trains and
    scripts/eval_probes.py --decoder-at answers_sinks_replay scores. replay_window: W of that regime, an integer >= 1
    (a window of 0 would be "rows_sinks" under another name: refused, as the probe scorer refuses it); ignored by
    every other regime. Or a last-turn name, "turn" / "turn<N>" (is "turn128"; ced/eval/replay_window.py): the whole
    last message before each assistant turn, read from the <|im_start|> tokens (im_start: their id, required then),
    capped at its last 512 / N positions (ced.eval.long_context.replay_positions, the suite's rule on rows of several
    documents). A document without chat tokens has no turn boundary: the replay starts at the document's first
    position in the row, so on span rows of plain documents "turn<N>" is replay N, position for position. SpanEval
    records the window's name there.

    Every evaluation also records, per row, the positions that ran the decoder (row_decoder_slots) and the part of the
    dec sums at span starts (row_start_*; SpanEval).
    """
    # Route on the config, not the class: a wrapped model (DDP, torch.compile, a fast-path class)
    # must not silently be scored as the control (review finding, 2026-10-03).
    inner = model
    while hasattr(inner, "module") or hasattr(inner, "_orig_mod"):
        inner = getattr(inner, "module", None) or getattr(inner, "_orig_mod")
    cfg = getattr(inner, "cfg", None)
    assert cfg is not None and cfg.arch in SLOT_ARCHES + ("control",), "evaluate() needs a model with cfg.arch"
    arch = cfg.arch
    if decoder_at not in DECODER_AT:
        raise ValueError(f"decoder_at {decoder_at!r}: None, 'every', 'rows', 'rows_sinks' or 'rows_sinks_replay'")
    if decoder_at is not None and arch not in EVERY_POSITION_ARCHES:
        raise ValueError(f"decoder_at {decoder_at!r} is for {EVERY_POSITION_ARCHES}, not {arch!r}")
    restricted = decoder_at in RESTRICTED
    if restricted and arch != "ced_v2":
        raise ValueError(f"decoder_at {decoder_at!r} is CED v2's restricted regime, not for {arch!r}")
    replay = decoder_at == "rows_sinks_replay"
    from ced.eval.replay_window import is_turn, parse_replay_window, replay_window_name

    turn = replay and is_turn(replay_window)  # the whole last turn before each span start, capped
    if replay and not turn and (isinstance(replay_window, bool) or not isinstance(replay_window, int) or replay_window < 1):
        raise ValueError(f"replay_window {replay_window!r}: decoder_at 'rows_sinks_replay' needs an integer >= 1 "
                         "(or a last-turn name: 'turn', 'turn<N>')")
    turn_max = parse_replay_window(replay_window)[1] if turn else None
    if turn and im_start is None:
        raise ValueError(f"replay_window {replay_window!r} reads the <|im_start|> tokens: pass im_start (their token id)")
    # 0: no replay positions (every other regime); a last-turn window is named in the result
    window = (replay_window_name(replay_window) if turn else replay_window) if replay else 0
    is_v1 = arch == "looped_ced"  # its decoder GDN layers take the decoder varlen boundaries
    looped = is_v1 or restricted  # the decoder at the rows' decoder positions (v1; CED v2 restricted)
    every = arch in EVERY_POSITION_ARCHES and not restricted  # v2 / (c): the decoder at every valid target
    n_sinks = cfg.decoder.n_sinks if decoder_at in ("rows_sinks", "rows_sinks_replay") else 0
    run_capacity = rows.seq_len if (n_sinks or window) else rows.capacity  # sinks / replay slots: one shape, room for all
    # A pass count for the looped arches and for the control with a gated second pass (ced/model/control.py, "Two
    # passes": pass 2 at every position, as it is trained; T = 1 is its pass 1 alone). None for every other model,
    # which is then called exactly as before (a control's config is read for the gate only if it has a loop section:
    # a wrapped or stub control without one is the plain control).
    looped_control = arch == "control" and getattr(getattr(cfg, "loop", None), "pass2_gate", "none") != "none"
    T = (cfg.loop.t_eval if T is None else T) if (arch in LOOPED_ARCHES or looped_control) else None
    loop1 = arch == "ced_v2" and T >= 2
    vocab = getattr(cfg, "vocab_size", None)
    if vocab is not None:
        top = max(int(rows.tokens.max()), int(rows.targets.max()))
        assert top < vocab, f"token id {top} is outside the model's vocabulary of {vocab}"

    from ced.train.positions import replay_positions, sink_positions, span_starts  # host-side masks

    device = _device(model)
    was_training = model.training
    model.eval()
    keys = ["dec_nats", "ctx_nats", "dec_bytes", "ctx_bytes", "dec_tokens", "ctx_tokens"]
    start_keys = ["start_nats", "start_bytes", "start_tokens"]  # the dec sums at span starts (SpanEval.row_start_*)
    has_decoder = every or looped
    diag_heads = (["aux"] + (["loop1"] if loop1 else [])) if every else []
    diag_keys = [f"{h}_{w}_nats" for h in diag_heads for w in ("dec", "ctx")]
    special_ids = rows.special_ids
    if special_ids is not None:
        keys += ["dec_special_nats", "ctx_special_nats", "dec_special_bytes", "ctx_special_bytes"]
    sums = {k: [] for k in keys + diag_keys + start_keys + (["decoder_slots"] if has_decoder else [])}
    segs = {k: [] for k in ["row", "doc"] + keys if not k.endswith("tokens")}
    with_classes = rows.target_class is not None  # per-class sums per segment (SpanEval.seg_class_*); the rest is unchanged
    if with_classes:
        segs.update(class_nats=[], class_bytes=[], class_tokens=[])
    check = {"max_abs_ce_diff": 0.0, "dec_nats_ref": 0.0, "dec_nats_fused": 0.0, "positions": 0} if fused_check else None
    if check is not None and check_head_precision(head_precision) != "fp32":
        check["head_precision"] = head_precision
    if check is not None and head_chunk is not None:
        check["head_chunk"] = int(head_chunk)
    assert not fused_check or chunked_head, "fused_check needs chunked_head"
    try:
        for start in range(0, len(rows), batch_size):
            batch = rows[start : start + batch_size]
            run = batch.dec_mask  # host: where the decoder runs in the rows' regimes
            if n_sinks:  # rows_sinks: the decoder also at each document's first n_sinks positions (not scored)
                run = run | sink_positions(batch.doc_ids, n_sinks)
            if turn:  # rows_sinks_replay, the last turn: the suite's rule (the same span starts; one <|im_start|> back)
                from ced.eval.long_context import replay_positions as turn_positions

                run = run | turn_positions(batch.target_valid & batch.dec_mask, batch.doc_ids, "turn", tokens=batch.tokens,
                                           im_start=im_start, turn_max=turn_max)
            elif window:  # rows_sinks_replay: and at the positions before each run of scored positions (not scored)
                run = run | replay_positions(batch.doc_ids, batch.target_valid & batch.dec_mask, window)
            tokens, doc_ids, dec = (x.to(device) for x in (batch.tokens, batch.doc_ids, run))
            autocast = torch.autocast(device.type, dtype=autocast_dtype, enabled=autocast_dtype is not None)
            diag = {}
            if every:
                varlen = None
                if fused_varlen:
                    from ced.train.varlen import to_device, varlen_for_batch

                    varlen = to_device(varlen_for_batch(batch.doc_ids, None, None), device)
                with autocast:
                    scores = _every_position_ce(model, inner, batch, tokens, doc_ids, batch.target_valid.to(device),
                                                batch.targets.to(device), T, loop1, varlen, chunked_head, check)
                ce = scores.pop("main").cpu()
                diag = {k: v.cpu() for k, v in scores.items()}
            elif chunked_head:
                varlen = None
                if fused_varlen:
                    from ced.train.varlen import to_device, varlen_for_batch

                    host = varlen_for_batch(batch.doc_ids, batch.dec_mask if is_v1 else None,
                                            rows.capacity if is_v1 else None)
                    varlen = to_device(host, device)
                with autocast:
                    ce = _scored_ce(model, inner, looped, batch, tokens, doc_ids, dec, batch.targets.to(device),
                                    T, run_capacity, varlen, check).cpu()
            else:
                with autocast:
                    if looped:
                        sched = ({"scored": (batch.target_valid & batch.dec_mask).to(device)}
                                 if getattr(inner, "schedule", None) is not None else {})
                        out = model(tokens, doc_ids, dec, T=T, capacity=run_capacity, **sched)
                        assert int(out.n_dropped.sum()) == 0, "decoder positions were dropped: raise rows.capacity"
                        assert torch.equal(out.kept, dec), "the decoder head did not run at the rows' decoder positions"
                    else:
                        out = model(tokens, doc_ids, dec, **({} if T is None else {"T": T}))
                ce = token_cross_entropy(out.logits, batch.targets.to(device)).cpu()

            valid = batch.target_valid
            on_dec = valid & batch.dec_mask
            on_ctx = valid & ~batch.dec_mask
            zero = torch.zeros((), dtype=torch.float64)
            nbytes = batch.target_bytes
            sums["dec_nats"].append(torch.where(on_dec, ce, zero).sum(1))
            sums["ctx_nats"].append(torch.where(on_ctx, ce, zero).sum(1))
            sums["dec_bytes"].append(torch.where(on_dec, nbytes, 0).sum(1))
            sums["ctx_bytes"].append(torch.where(on_ctx, nbytes, 0).sum(1))
            sums["dec_tokens"].append(on_dec.long().sum(1))
            sums["ctx_tokens"].append(on_ctx.long().sum(1))
            on_start = span_starts(batch.doc_ids, on_dec)  # the first scored position of each span / assistant turn
            sums["start_nats"].append(torch.where(on_start, ce, zero).sum(1))
            sums["start_bytes"].append(torch.where(on_start, nbytes, 0).sum(1))
            sums["start_tokens"].append(on_start.long().sum(1))
            if has_decoder:  # where the decoder ran: every valid target, or the regime's positions
                sums["decoder_slots"].append((valid if every else run).long().sum(1))
            for name, head_ce in diag.items():
                sums[f"{name}_dec_nats"].append(torch.where(on_dec, head_ce, zero).sum(1))
                sums[f"{name}_ctx_nats"].append(torch.where(on_ctx, head_ce, zero).sum(1))
            per_pos = {"dec_nats": torch.where(on_dec, ce, zero), "ctx_nats": torch.where(on_ctx, ce, zero),
                       "dec_bytes": torch.where(on_dec, nbytes, 0), "ctx_bytes": torch.where(on_ctx, nbytes, 0)}
            if special_ids is not None:
                special = torch.isin(batch.targets, special_ids)
                for name, on in (("dec", on_dec & special), ("ctx", on_ctx & special)):
                    sums[f"{name}_special_nats"].append(torch.where(on, ce, zero).sum(1))
                    sums[f"{name}_special_bytes"].append(torch.where(on, nbytes, 0).sum(1))
                    per_pos[f"{name}_special_nats"] = torch.where(on, ce, zero)
                    per_pos[f"{name}_special_bytes"] = torch.where(on, nbytes, 0)
            if with_classes:  # (B, L, 4, 2): class of the target token, decoder / context position
                tc = batch.target_class.long()
                cell = (tc[..., None, None] == torch.arange(4)[:, None]) & torch.stack([on_dec, on_ctx], dim=-1)[:, :, None, :]
                per_cls = {"class_nats": torch.where(cell, ce[..., None, None], zero),
                           "class_bytes": torch.where(cell, nbytes[..., None, None], 0), "class_tokens": cell.long()}
            for r in range(len(batch)):  # per (row, document) segment; documents are contiguous in a row
                docs, inverse = torch.unique_consecutive(batch.doc_ids[r], return_inverse=True)
                has = torch.zeros(len(docs), dtype=torch.long).index_add_(0, inverse, valid[r].long()) > 0
                segs["row"].append(torch.full((int(has.sum()),), start + r, dtype=torch.long))
                segs["doc"].append(docs[has])
                for k, v in per_pos.items():
                    acc = torch.zeros(len(docs), dtype=v.dtype).index_add_(0, inverse, v[r])
                    segs[k].append(acc[has])
                if with_classes:
                    for k, v in per_cls.items():
                        acc = torch.zeros((len(docs), 4, 2), dtype=v.dtype).index_add_(0, inverse, v[r])
                        segs[k].append(acc[has])
    finally:
        model.train(was_training)

    row = {k: torch.cat(v) for k, v in sums.items()}
    seg = {f"seg_{k}": torch.cat(v) for k, v in segs.items() if v}
    return _span_eval(
        rows, row, seg, check, arch=arch,
        # a control with a looped middle (model.loop.recur_layers) is given no T above and runs its own default
        # (loop.t_eval, or CED_LOOP_T: ced/model/control.py HybridLM.passes): the record says which
        T=inner.passes(None) if (T is None and arch == "control" and getattr(inner, "recur", None) is not None) else T,
        decoder_at="every" if every else (decoder_at if restricted else ("rows" if looped else None)),
        replay_window=window if replay else None)


def _span_eval(rows: EvalRows, row: dict, seg: dict, check: dict | None, arch: str, T: int | None,
               decoder_at: str | None, replay_window: int | str | None) -> SpanEval:
    """evaluate's result from its per-row sums over `rows` (row: evaluate's names, "dec_nats" ... "decoder_slots", each a
    tensor over every row in order), its per-segment sums (seg: "seg_row", "seg_doc", "seg_dec_nats", ...; seg_group is
    made here) and the fused check's running sums (check; None without it): the totals, the bpbs, the clusters and the
    fingerprint of `rows`. The one place they are formed, for evaluate and for join_batches (the sharded evals, E1)."""
    dec_nats, ctx_nats = row["dec_nats"].sum(), row["ctx_nats"].sum()
    dec_bytes, ctx_bytes = int(row["dec_bytes"].sum()), int(row["ctx_bytes"].sum())
    special = {f"row_{k}": v for k, v in row.items() if "special" in k}
    diag_heads = [h for h in ("aux", "loop1") if f"{h}_dec_nats" in row]
    has_decoder = "decoder_slots" in row
    seg = dict(seg)
    seg["seg_group"] = rows.doc_group[seg["seg_doc"]] if rows.doc_group is not None else seg["seg_doc"].clone()
    if check is not None:
        ref_bpb, fused_bpb = bpb(check["dec_nats_ref"], dec_bytes), bpb(check["dec_nats_fused"], dec_bytes)
        check.update(dec_bpb_ref_fp32=ref_bpb, dec_bpb_fused_fp32=fused_bpb, dec_bpb_abs_diff=abs(fused_bpb - ref_bpb),
                     within_criteria=check["max_abs_ce_diff"] <= 1e-4 and abs(fused_bpb - ref_bpb) <= 1e-6)
    diagnostics = {}
    for name in diag_heads:
        d_nats, c_nats = row[f"{name}_dec_nats"], row[f"{name}_ctx_nats"]
        diagnostics.update({
            f"{name}_bpb": bpb(d_nats.sum(), dec_bytes),
            f"{name}_all_bpb": bpb(d_nats.sum() + c_nats.sum(), dec_bytes + ctx_bytes),
            f"row_{name}_dec_nats": d_nats,
            f"row_{name}_ctx_nats": c_nats,
        })
    return SpanEval(
        dec_bpb=bpb(dec_nats, dec_bytes),
        ctx_bpb=bpb(ctx_nats, ctx_bytes),
        all_bpb=bpb(dec_nats + ctx_nats, dec_bytes + ctx_bytes),
        n_dec_tokens=int(row["dec_tokens"].sum()),
        n_ctx_tokens=int(row["ctx_tokens"].sum()),
        n_dec_bytes=dec_bytes,
        n_ctx_bytes=ctx_bytes,
        row_dec_nats=row["dec_nats"],
        row_ctx_nats=row["ctx_nats"],
        row_dec_bytes=row["dec_bytes"],
        row_ctx_bytes=row["ctx_bytes"],
        row_dec_tokens=row["dec_tokens"],
        row_ctx_tokens=row["ctx_tokens"],
        arch=arch,
        T=T,
        rows_fingerprint=rows.fingerprint(),
        row_cluster=row_clusters(rows),
        fused_check=check,
        decoder_at=decoder_at,
        replay_window=replay_window,
        row_decoder_slots=row["decoder_slots"] if has_decoder else None,
        row_start_nats=row["start_nats"],
        row_start_bytes=row["start_bytes"],
        row_start_tokens=row["start_tokens"],
        **diagnostics,
        **special,
        **seg,
    )


# The fused check's running sums (evaluate: _update_fused_check, _scored_ce_cp), and what _span_eval derives from them
FUSED_CHECK_SUMS = ("max_abs_ce_diff", "dec_nats_ref", "dec_nats_fused", "positions")
FUSED_CHECK_DERIVED = ("dec_bpb_ref_fp32", "dec_bpb_fused_fp32", "dec_bpb_abs_diff", "within_criteria")


def join_batches(rows: EvalRows, parts: list, batch_size: int) -> SpanEval:
    """evaluate(model, rows, batch_size=b, ...) put together from evaluate's results on the batches of rows, each scored
    alone: parts [(start, evaluate(model, rows[start : start + b], batch_size=b, ...))] for EVERY batch of rows, in order
    (start 0, b, 2b, ...; the last batch may be shorter; b = batch_size), all with the same arguments. The sharded evals (E1,
    ced/train/sharded_eval.py) score each rank's batches so and join them on rank 0.

    Bit for bit evaluate's result, when every batch's numbers are those evaluate computes for it in its own loop (the same
    rows, the same batch, the same model: a row is scored within its batch alone): the per-row and per-segment sums are
    put in row order (each segment's row moved by its batch's start), the totals, bpbs, clusters and the fingerprint
    are formed by evaluate's own code over all of rows (_span_eval), and the fused check's running sums are folded batch
    by batch in order, as evaluate adds them (0.0 + x is x, so a batch's own sum is the term evaluate adds; max is exact).
    A part that is not one batch of the loop (two batches in one part) keeps every number but the fused check's sums,
    whose order of addition would change: refused, by its length. Raises ValueError when the parts do not cover rows in
    order, differ in what they hold, or were scored on other rows than these (each part's rows_fingerprint, made by
    evaluate on its batch, against the same batch of `rows`: a rank that scored another set's batch of the same length
    is refused, never joined; the cost is one more pass of the fingerprint's hash over the rows)."""
    if not parts:
        raise ValueError("join_batches: no parts")
    b = int(batch_size)
    starts = [int(s) for s, _ in parts]
    sizes = [len(e.row_dec_nats) for _, e in parts]
    if starts != list(range(0, len(rows), b)) or sizes != [min(b, len(rows) - s) for s in starts]:
        raise ValueError(f"join_batches: parts at rows {starts} of {sizes} rows are not the batches of {b} of {len(rows)} "
                         f"rows in order")
    first = parts[0][1]
    fields = [f.name for f in dataclasses.fields(SpanEval)]
    per_row = [f for f in fields if f.startswith("row_") and f != "row_cluster"]  # recomputed over all of rows
    per_seg = [f for f in fields if f.startswith("seg_") and f != "seg_group"]  # seg_group: made by _span_eval
    known = set(per_row) | set(per_seg) | {
        "row_cluster", "seg_group", "dec_bpb", "ctx_bpb", "all_bpb", "n_dec_tokens", "n_ctx_tokens", "n_dec_bytes",
        "n_ctx_bytes", "aux_bpb", "aux_all_bpb", "loop1_bpb", "loop1_all_bpb", "rows_fingerprint", "fused_check", "arch",
        "T", "decoder_at", "replay_window"}
    unknown = sorted(set(fields) - known)
    if unknown:  # a field SpanEval gained that this join does not know how to put together: never guessed
        raise ValueError(f"join_batches: SpanEval fields {unknown} are not known here")
    same = ("arch", "T", "decoder_at", "replay_window")
    for _, e in parts[1:]:
        odd = [k for k in same if getattr(e, k) != getattr(first, k)]
        odd += [k for k in per_row + per_seg + ["fused_check"] if (getattr(e, k) is None) != (getattr(first, k) is None)]
        if odd:
            raise ValueError(f"join_batches: the parts differ in {odd}")
    for s, e in parts:  # the rows each part was scored on are these rows' batch at its start
        if e.rows_fingerprint != rows[s : s + len(e.row_dec_nats)].fingerprint():
            raise ValueError(f"join_batches: the part at row {s} was scored on other rows than these (its fingerprint "
                             f"differs)")
    row = {f[len("row_"):]: torch.cat([getattr(e, f) for _, e in parts]) for f in per_row if getattr(first, f) is not None}
    seg = {f: torch.cat([getattr(e, f) + s if f == "seg_row" else getattr(e, f) for s, e in parts]) for f in per_seg
           if getattr(first, f) is not None}
    check = None
    if first.fused_check is not None:
        check = {k: (0 if k == "positions" else 0.0) for k in FUSED_CHECK_SUMS}
        check.update({k: v for k, v in first.fused_check.items() if k not in FUSED_CHECK_SUMS + FUSED_CHECK_DERIVED})
        for _, e in parts:  # evaluate's own steps, batch by batch (_update_fused_check)
            c = e.fused_check
            check["max_abs_ce_diff"] = nan_max((check["max_abs_ce_diff"], c["max_abs_ce_diff"]))  # a NaN shard stays NaN
            check["dec_nats_ref"] += c["dec_nats_ref"]
            check["dec_nats_fused"] += c["dec_nats_fused"]
            check["positions"] += c["positions"]
    return _span_eval(rows, row, seg, check, arch=first.arch, T=first.T, decoder_at=first.decoder_at,
                      replay_window=first.replay_window)


