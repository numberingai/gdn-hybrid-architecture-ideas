# paired comparison and eval-set size
# --------------------------------------------------------------------------------------------


@dataclass
class PairedDifference:
    metric: str
    diff: float  # bpb_a - bpb_b
    se: float  # standard error of diff over eval rows, rows treated as independent
    bpb_a: float
    bpb_b: float
    n_rows: int  # rows with scored bytes
    row_std: float  # spread of the per-row difference, in bpb (rows independent)
    # Over clusters (rows of the same document or environment are not independent).
    # row_std_clustered = se_clustered * sqrt(n_rows): the per-row spread that gives the clustered
    # SE, the input to eval_set_size for a set built the same way (`eval_set_size_for`).
    se_clustered: float = float("nan")
    n_clusters: int = 0
    row_std_clustered: float = float("nan")


def _ratio_se(y: torch.Tensor, x: torch.Tensor, groups: torch.Tensor | None) -> tuple[float, float, int]:
    """(estimate, delta-method SE, number of units) of sum(y) / sum(x) over units: the rows, or
    the row groups when `groups` is given (y and x summed per group first). Units with x = 0 are
    left out."""
    if groups is not None:
        _, inv = torch.unique(groups, return_inverse=True)
        y = torch.zeros(int(inv.max()) + 1, dtype=torch.float64).index_add_(0, inv, y.double())
        x = torch.zeros(int(inv.max()) + 1, dtype=torch.float64).index_add_(0, inv, x.double())
    keep = x > 0
    y, x = y.double()[keep], x.double()[keep]
    n = int(keep.sum())
    if n == 0:
        return float("nan"), float("nan"), 0
    est = float(y.sum() / x.sum())
    if n < 2:
        return est, float("nan"), n
    resid = y - est * x
    se = math.sqrt(float(resid.pow(2).sum()) / (n - 1) / n) / float(x.mean())
    return est, se, n


def paired_difference(a: SpanEval, b: SpanEval, metric: str = "dec", special_bytes: bool = True) -> PairedDifference:
    """bpb(a) - bpb(b) on the same rows, with its standard error from per-row paired differences.

    Both bpbs share the denominator (the same scored bytes), so the difference is a ratio
    estimator over rows:

        diff = sum_r y_r / sum_r x_r,   y_r = (nats_a,r - nats_b,r) / ln 2,   x_r = bytes_r
        se   = row_std / sqrt(n),       row_std = std_r(y_r - diff * x_r) / mean_r(x_r)

    (the delta-method variance of a ratio, treating rows as independent draws). With equal bytes
    per row, row_std is the standard deviation of the per-row bpb difference. Rows without scored
    bytes are left out. The SE covers eval-set sampling only; training-seed noise needs repeat
    runs. Identical models give diff = 0 and se = 0.

    Rows are not independent: every row boundary splits a document, and agent documents share
    environments. se_clustered is the same estimator over clusters (y and x summed per cluster):
    over (row, document) segments in each segment's own group when the evaluations carry segments,
    else over rows in their dominant document's group (`row_cluster`); report it.
    special_bytes=False: special tokens count 0 bytes.
    """
    assert a.rows_fingerprint == b.rows_fingerprint, "the two evaluations were not run on the same rows"
    nats_a, bytes_a = a.row_sums(metric, special_bytes)
    nats_b, bytes_b = b.row_sums(metric, special_bytes)
    assert torch.equal(bytes_a, bytes_b), "scored bytes differ per row: not the same positions"
    has_bytes = bytes_a > 0
    n = int(has_bytes.sum())
    x = torch.where(has_bytes, bytes_a, 0).double()
    y = torch.where(has_bytes, nats_a - nats_b, 0.0) / LN2
    total_bytes = float(x.sum())
    if n == 0:
        nan = float("nan")
        return PairedDifference(metric, nan, nan, nan, nan, 0, nan)
    diff = float(y.sum()) / total_bytes
    if n > 1:
        resid = torch.where(has_bytes, y - diff * x, 0.0)
        row_std = math.sqrt(float(resid.pow(2).sum()) / (n - 1)) / (total_bytes / n)
        se = row_std / math.sqrt(n)
    else:
        row_std = se = float("nan")
    out = PairedDifference(
        metric=metric, diff=diff, se=se, n_rows=n, row_std=row_std,
        bpb_a=bpb(nats_a.sum(), bytes_a.sum()), bpb_b=bpb(nats_b.sum(), bytes_b.sum()),
    )
    seg_a, seg_b = a.seg_sums(metric, special_bytes), b.seg_sums(metric, special_bytes)
    if seg_a is not None and seg_b is not None:  # per (row, document) segment, its own group
        assert torch.equal(a.seg_row, b.seg_row) and torch.equal(a.seg_doc, b.seg_doc)
        (sa, xs), (sb, _) = seg_a, seg_b
        _, se_c, k = _ratio_se((sa - sb) / LN2, xs, a.seg_group)
        out.se_clustered, out.n_clusters, out.row_std_clustered = se_c, k, se_c * math.sqrt(n)
    elif a.row_cluster is not None:  # older evaluations: each row in its dominant document's group
        assert b.row_cluster is None or torch.equal(a.row_cluster, b.row_cluster)
        _, se_c, k = _ratio_se(y, x, a.row_cluster)
        out.se_clustered, out.n_clusters, out.row_std_clustered = se_c, k, se_c * math.sqrt(n)
    return out


def bpb_se(e: SpanEval, metric: str = "dec", clustered: bool = True, special_bytes: bool = True) -> float:
    """Standard error of one model's bpb from eval-set sampling (absolute level, not a paired
    difference), over clusters when the evaluation carries them and `clustered`, else over rows."""
    if clustered and e.seg_sums(metric, special_bytes) is not None:
        nats, nbytes = e.seg_sums(metric, special_bytes)
        return _ratio_se(nats / LN2, nbytes, e.seg_group)[1]
    nats, nbytes = e.row_sums(metric, special_bytes)
    groups = e.row_cluster if clustered else None
    return _ratio_se(nats / LN2, nbytes, groups)[1]


def eval_set_size_for(pilot: PairedDifference, target_se_bpb: float, **kwargs) -> int:
    """`eval_set_size` from a pilot's paired difference, using its clustered per-row spread when it
    has one (a set built the same way has the same rows per cluster)."""
    std = pilot.row_std_clustered if pilot.n_clusters > 1 else pilot.row_std
    return eval_set_size(target_se_bpb, std, **kwargs)


def eval_set_size(
    target_se_bpb: float,
    per_row_diff_std: float,
    *,
    pilot_scored_bytes_per_row: float | None = None,
    scored_bytes_per_row: float | None = None,
    min_rows: int = 30,
) -> int:
    """Rows needed for the paired bpb difference to have standard error <= target_se_bpb.

        se = row_std / sqrt(n)   =>   n = ceil((row_std / target_se_bpb)^2)

    per_row_diff_std: `PairedDifference.row_std` from a pilot: two models of the kind being compared
        (e.g. two sweep rows), on rows of the same kind (L, span fraction, domain). It depends on how
        different the two models are, so measure it on a realistic pair, not a model against itself.

    If the pilot scored a different number of bytes per row than the planned eval, pass both byte
    counts. The std is then scaled by sqrt(pilot / planned). Two cases where this matters:
    - The pilot scored all positions, but the eval scores only the ~25% at decoder positions. The
      std then grows by about 2x, and the rows needed by about 4x.
    - The pilot used shorter rows than the planned eval.
    The scaling is exact when token-level differences are independent within a row and equally
    noisy at decoder and context positions. Positive correlation within a row makes it
    conservative: it over-estimates the rows needed. In the CPU pilot of 2026-10-03 (tiny models,
    held-out Python code, L = 256), the dec/all row_std ratio was 1.49 against 2.00 predicted, so
    it asked for 1.8x the rows. It under-estimates if differences are noisier at decoder
    positions than elsewhere. Confirm with a pilot at the real setting.

    min_rows: a floor so that the normal approximation behind the SE is reasonable.

    Example with made-up numbers: a pilot row_std of 0.004 bpb on all positions, decoder positions
    at 25% of bytes, and a target SE of 0.001 bpb give ceil((0.004 * 2 / 0.001)^2) = 64 rows.
    """
    std = per_row_diff_std
    if pilot_scored_bytes_per_row is not None or scored_bytes_per_row is not None:
        assert pilot_scored_bytes_per_row and scored_bytes_per_row, "pass both byte counts or neither"
        std = std * math.sqrt(pilot_scored_bytes_per_row / scored_bytes_per_row)
    return max(min_rows, math.ceil((std / target_se_bpb) ** 2 - 1e-9))
