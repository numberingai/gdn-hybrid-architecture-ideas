"""Phase 2 / sweep evaluator: bits per byte at decoder positions on fixed-seed spans.

Why this metric (decided 2026-10-02, "Phase 2 evaluation"):

- Which positions are decoder positions changes what Looped-CED computes: a decoder position is
  scored by the looped decoder head and offers own KVs, a context position is scored by the aux
  encoder head and offers a memory KV. A fair eval must therefore fix the decoder positions
  independently of the model. Here they come from the training span sampler
  (`ced.train.data.sample_spans`: log-normal lengths, placement from the counter RNG and the row
  length only) with a fixed eval seed, so every model in a comparison sees the same mask.
- The control has no decoder. It is scored at the same target positions by its single head, so
  "decoder-position bpb" compares the same tokens across Looped-CED and the control.
- Primary: `dec_bpb` (decoder positions). Secondary: `ctx_bpb` (context positions; for Looped-CED
  this is the aux encoder head). `all_bpb` is the whole-row number.
- CED v2 and the second-pass control (architecture spec v2; section 4) run the decoder (pass 2) at
  EVERY scored position, although pretraining runs it on 25%: the model gets dec_mask = the valid
  targets and capacity L, and dec_bpb, ctx_bpb and all_bpb all come from the main head (a slot's
  output does not depend on which other positions are slots, so dec_bpb is the same number the rows'
  own decoder mask would give). Diagnostics at the same positions: `aux_bpb` / `aux_all_bpb`, the
  aux (encoder) head, i.e. drafter quality; and for CED v2 with T >= 2, `loop1_bpb` /
  `loop1_all_bpb`, the loop-1 readout RMSNorm_dec(HC.finish(Y_1)) through the final head.
- Chat trajectories use roles instead of spans (`build_role_eval_rows`): a position is a decoder
  position iff its next token is an assistant token in the same document. Nothing is capped: the
  model gets capacity = L, so no assistant position is dropped.
- Only ~25% of targets are decoder positions on span rows, so the eval set has to be larger than an
  all-position eval for the same noise. Comparisons are paired: both models are scored on the same
  rows, and the standard error comes from per-row differences, which cancel the document
  difficulty shared by both models (`paired_difference`). `eval_set_size` turns a pilot
  measurement of the per-row spread into a row count.

Rows. Documents are concatenated in the order given and cut into rows of L + 1 tokens that overlap
by one token (the last target of a row is the first input of the next), as the training packer
does, so every in-document target is scored exactly once. A target that belongs to the next
document is invalid, so the first token of every document is never scored. The last row is padded
with an inert padding document whose targets are all invalid. Rows are a pure function of
(documents, L, capacity, span parameters, seed) and never look at a model.

    bpb = sum of CE (nats) / (ln 2 * sum of UTF-8 bytes of the scored target tokens)

This is evaluation code, not the training path, but it keeps fixed shapes anyway (masks and
`torch.where`, no boolean indexing) so that it runs unchanged on the fast path.
"""

